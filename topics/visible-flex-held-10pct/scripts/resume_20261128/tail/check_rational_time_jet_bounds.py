#!/usr/bin/env python3
"""Independent exact algebra checks for the new time-majorant implementation.

The probes below are formal rational jets, not accepted surface data. SymPy
differentiates the signed implicit-chart expressions independently of the
nonnegative Taylor-series implementation. No low-lambda field or solver is
loaded, and this report cannot be a positive complete-field certificate.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path
import sys

import sympy as sp

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import rational_time_jet_bounds as bound


def sq(value):
    return Q(int(value.p), int(value.q))


def ref(path):
    path = Path(path).resolve()
    return dict(path=str(path), sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def run_checks():
    checks = []
    def check(name, value):
        if not value:
            raise ArithmeticError(name)
        checks.append(name)

    # Signed differentiation uses independently supplied formal X jets.
    # The rational trig pair lies on the exact circle, and its derivatives
    # are generated by ds/dpsi=3c, dc/dpsi=-3s.
    e, ep, epp, sn, co = sp.symbols('e ep epp sn co')
    x = {(r,j):sp.Symbol('x_%d_%d'%(r,j)) for r,j in bound.NEEDED}
    def D(expression):
        value = 3*co*sp.diff(expression,sn)-3*sn*sp.diff(expression,co)
        for (r,j), symbol in x.items():
            if (r,j+1) in x:
                value += x[r,j+1]*sp.diff(expression,symbol)
        return sp.cancel(value)
    rho = 1-e*co
    V = 1/rho
    U = ep*sn/(3*rho)
    A = (epp*sn/3+2*ep*co*U-3*e*sn*U*U)/rho
    starts = [x[0,0], x[1,0]+U*x[0,1],
              x[2,0]+2*U*x[1,1]+U*U*x[0,2]+A*x[0,1]]
    exact_expressions = {}
    for r, expression in enumerate(starts):
        for j in range(5-r):
            exact_expressions[r,j] = expression
            if j < 4-r:
                expression = sp.cancel(V*D(expression))
    E = [Q(2,7),Q(3,11),Q(5,13)]
    absolute = {(r,j):Q(2+3*r+5*j,7+r+j) for r,j in bound.NEEDED}
    majorants, inverse = bound.physical_theta_jets(absolute,E)
    cases = 0
    for sign_e in (-1,1):
        for sign_ep in (-1,1):
            for sign_sin in (-1,1):
                substitution = {e:sign_e*sp.Rational(E[0].numerator,E[0].denominator),
                    ep:sign_ep*sp.Rational(E[1].numerator,E[1].denominator),
                    epp:-sp.Rational(E[2].numerator,E[2].denominator),
                    sn:sp.Rational(3*sign_sin,5),co:sp.Rational(4,5)}
                for (r,j), symbol in x.items():
                    q = absolute[r,j]*(-1 if (r+j)%2 else 1)
                    substitution[symbol] = sp.Rational(q.numerator,q.denominator)
                for key, expression in exact_expressions.items():
                    value = abs(sq(expression.subs(substitution)))
                    check('signed_inverse_chart_case_%d_jet_%d_%d'%(cases,*key),
                          value <= majorants[key])
                cases += 1
    zero_chart, _ = bound.physical_theta_jets(absolute,[Q(0)]*3)
    check('exact_identity_chart_all_twelve_derivatives',zero_chart == absolute)

    # With no chart and one exact angular mode, the genuine phase frequency
    # is k-m. The general triangle bound must dominate its exact square for
    # every six-jet. This catches missing angular orders and phase factors.
    k, omega, m = Q(1,2),Q(4,5),Q(9)
    mode = {(r,j):Q(2)**r*m**j for r,j in bound.NEEDED}
    temporal = bound.time_bounds(mode,phase_end=omega,curvature=k,
        center_norm=Q(0),radius_lower=Q(3,10))
    for key,value in temporal['time_second_six_jets'].items():
        check('full_angular_mode_time_second_%d_%d'%key,
              value >= omega**2*(k-m)**2*mode[key])
    for q in (Q(0),Q(1),Q(2),Q(1,3),Q(10**30+1,10**20+3)):
        result = bound.sqrt_upper(q)
        check('dyadic_square_upper_'+str(q),result*result >= q)
    eta,tau,V0 = Q(1,2000000),Q(1,1000000),Q(7,3)
    n = bound.minimum_metric_intervals(eta,tau,V0)
    check('exact_time_grid_satisfies_Gram_gate',eta+V0*V0/Q(4*n*n) <= tau)
    check('exact_time_grid_is_minimal',n == 1 or eta+V0*V0/Q(4*(n-1)**2) > tau)
    # Cross-check the independently already-reviewed material curvature
    # bounds through order two on a literal rational parameter list. This
    # is scalar algebra only, not any existing accepted-field rerun.
    sys.path.insert(0,str(HERE.parent/'analytic'))
    import prefix_physical_theta_c2_bounds as original
    coefficients = [Q(1,100),-Q(1,10000),Q(1,1000000)]
    settings = dict(homotopy=Q(1),halfwidth=Q(27,40),transition=Q(3,10),curvature=Q(1,2))
    newer = bound.true_core_bounds(coefficients,**settings)
    older = original.true_core_pair(coefficients,coefficients,**settings)
    for j,key in enumerate(('kappa_absolute','kappa_u_absolute','kappa_uu_absolute')):
        check('old_and_new_exact_curvature_'+str(j),newer['kappa_material_derivatives'][j] == older[key])
    check('true_core_position_normalization_bound',newer['gamma_material_derivatives'][0] == Q(44,35))
    return dict(status='exact_new_time_majorant_algebra_checks_passed',
        checks=checks,check_count=len(checks),signed_chart_cases=cases,
        signed_chart_jets_per_case=len(bound.NEEDED),
        new_math_source=ref(bound.__file__),checker_source=ref(__file__),
        earlier_curvature_scalar_source=ref(original.__file__),
        exact_uniform_metric_grid_intervals=n,
        all_arithmetic_exact=True,formal_jets_are_accepted_field=False,
        actual_surface_or_Gamma5_oracle_executed=False,BVP_or_native_called=False,
        complete_field_time_constants_certified=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,required=True)
    args = parser.parse_args()
    result = run_checks()
    args.out.parent.mkdir(parents=True,exist_ok=True)
    if args.out.exists():
        raise FileExistsError('Do not overwrite an earlier exact algebra receipt')
    args.out.write_text(json.dumps(result,indent=2,allow_nan=False)+'\n')
    print(json.dumps(dict(status=result['status'],checks=result['check_count'],
        result=ref(args.out))),flush=True)


if __name__ == '__main__':
    main()
