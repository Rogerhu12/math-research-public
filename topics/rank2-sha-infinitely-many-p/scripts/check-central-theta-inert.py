#!/usr/bin/env python3
"""Exact inert-prime samples for the fixed central theta diagonal.

No CLS table, ordinary-p calibration, or Sha hypothesis is used.
The primitive conductor orbit is generated by -3 and -2+i. Its possible
CM-unit ambiguity changes the output by a unit and never its valuation.
Usage: python check-central-theta-inert.py 3 [max_m] [precision]
"""
from collections import defaultdict
from fractions import Fraction
from functools import lru_cache
from math import comb, factorial
import json
import sys
import time
from flint import fq_default_ctx, fmpz_mod_poly_ctx, fmpz_poly

P=int(sys.argv[1])
assert P in (3,7,11)
MAX_M=int(sys.argv[2]) if len(sys.argv)>2 else P+2
PREC=int(sys.argv[3]) if len(sys.argv)>3 else 10
assert PREC>0
NEWTON_STEPS=(PREC-1).bit_length()
MOD=P**PREC
DEG=32
START=time.monotonic()
FIELD_POLYS={
 3:[2,1,0,1,2,1,2,0,0,0,0,2,2]+[0]*19+[1],
 7:[1,0,0,1]+[0]*28+[1],
 11:[2]+[0]*7+[1]+[0]*23+[1],
}
FIELD_POLY=FIELD_POLYS[P]
assert len(FIELD_POLY)==33
Fp_poly=fmpz_mod_poly_ctx(P)
FF=fq_default_ctx(modulus=Fp_poly(FIELD_POLY),var="a")
RP=fmpz_mod_poly_ctx(MOD)
R_MODULUS=RP(FIELD_POLY)

class R:
    """The finite unramified ring (Z/p^PREC)[a]/FIELD_POLY."""

    __slots__ = ("v",)

    def __init__(self, value=0):
        if isinstance(value, R):
            self.v = value.v
        elif isinstance(value, int):
            self.v = RP([value % MOD])
        else:
            self.v = RP(value) % R_MODULUS

    @staticmethod
    def coerce(value):
        return value if isinstance(value, R) else R(value)

    def __add__(self, other):
        other = self.coerce(other)
        return R(self.v + other.v)

    __radd__ = __add__

    def __neg__(self):
        return R(-self.v)

    def __sub__(self, other):
        return self + (-self.coerce(other))

    def __rsub__(self, other):
        return self.coerce(other) - self

    def __mul__(self, other):
        other = self.coerce(other)
        return R((self.v * other.v) % R_MODULUS)

    __rmul__ = __mul__

    def __pow__(self, exponent):
        assert exponent >= 0
        ans, base = R(1), self
        while exponent:
            if exponent & 1:
                ans *= base
            base *= base
            exponent >>= 1
        return ans

    def inverse(self):
        residue = FF([int(c) % P for c in self.v.coeffs()])
        assert residue, "nonunit denominator"
        b = R([int(c) for c in residue.inverse().to_list()])
        # Each Newton step doubles the exponent of p in the accuracy.
        for _ in range(NEWTON_STEPS):
            b = b * (2 - self * b)
        assert self * b == 1
        return b

    def __truediv__(self, other):
        return self * self.coerce(other).inverse()

    def __rtruediv__(self, other):
        return self.coerce(other) / self

    def __eq__(self, other):
        return self.v == self.coerce(other).v

    def __bool__(self):
        return bool(self.v)

    def coeffs(self):
        a = [int(c) for c in self.v.coeffs()]
        return a + [0] * (DEG - len(a))

    def scalar(self):
        a = self.coeffs()
        assert not any(a[1:]), "trace did not descend to the base ring"
        return a[0]

    def residue(self):
        return FF([int(c) % P for c in self.v.coeffs()])


def ring_lift(a):
    return R([int(c) for c in a.to_list()])


def neg(A):
    return None if A is None else (A[0], -A[1])


def add(A, B):
    """Usual group law; used only when the slope denominator is a unit."""
    if A is None:
        return B
    if B is None:
        return A
    x, y = A
    xx, yy = B
    if x == xx:
        if y == -yy:
            return None
        assert y == yy
        slope = (3*x*x - 17)/(2*y)
    else:
        slope = (yy-y)/(xx-x)
    X = slope*slope-x-xx
    Y = -y+slope*(x-X)
    return X, Y


def mul(n, A):
    if n < 0:
        return mul(-n, neg(A))
    out = None
    while n:
        if n & 1:
            out = add(out, A)
        A = add(A, A)
        n >>= 1
    return out


def cm_i(A, i):
    return None if A is None else (-A[0], i*A[1])


def curve_check(A):
    if A is not None:
        x, y = A
        assert y*y == x*x*x-17*x


def cocycle_add(A, B):
    """Add (x,y,U), using E1*(A+B)=E1*(A)+E1*(B)+slope."""
    if A is None:
        return B
    if B is None:
        return A
    x, y, u = A
    xx, yy, uu = B
    if x == xx:
        if y == -yy:
            return None
        assert y == yy
        slope = (3*x*x-17)/(2*y)
    else:
        slope = (yy-y)/(xx-x)
    X = slope*slope-x-xx
    Y = -y+slope*(x-X)
    return X, Y, u+uu+slope


def cocycle_mul(n, A):
    assert n >= 0
    out = None
    while n:
        if n & 1:
            out = cocycle_add(out, A)
        A = cocycle_add(A, A)
        n >>= 1
    return out


def normalized_u(A):
    """[34]A=(0,0) and U((0,0))=0, hence U(A)=-r_34/34."""
    x, y = A
    B = cocycle_mul(34, (x, y, R(0)))
    assert B is not None and B[0] == 0 and B[1] == 0
    return -B[2]/34


def gen_minus3(A):
    B = cocycle_add(cocycle_add(A, A), A)
    return B[0], -B[1], -B[2]


def gen_minus2_plus_i(A, i):
    B = cocycle_add(A, A)
    minus2 = (B[0], -B[1], -B[2])
    iA = (-A[0], i*A[1], -i*A[2])
    return cocycle_add(minus2, iA)


# Integral division polynomial psi_17.  For even n, f_n=psi_n/(2y).
X = fmpz_poly([0, 1])
Y2 = X**3-17*X


@lru_cache(None)
def division_part(n):
    if n == 0:
        return fmpz_poly([0])
    if n in (1, 2):
        return fmpz_poly([1])
    if n == 3:
        return 3*X**4-102*X**2-289
    if n == 4:
        return 2*(X**6-85*X**4-1445*X**2+4913)
    if n % 2 == 0:
        m = n//2
        return division_part(m)*(
            division_part(m+2)*division_part(m-1)**2
            - division_part(m-2)*division_part(m+1)**2)
    m = (n-1)//2
    left = division_part(m+2)*division_part(m)**3
    right = division_part(m-1)*division_part(m+1)**3
    return 16*Y2**2*left-right if m % 2 == 0 else left-16*Y2**2*right


def polynomial_eval(coefficients, x):
    ans = R(0)
    for c in reversed(coefficients):
        ans = ans*x+int(c)
    return ans


def lift_17_point(A):
    coeff = division_part(17).coeffs()
    deriv = division_part(17).derivative().coeffs()
    x, y = map(ring_lift, A)
    for _ in range(NEWTON_STEPS):
        x -= polynomial_eval(coeff, x)/polynomial_eval(deriv, x)
    assert not polynomial_eval(coeff, x)
    for _ in range(NEWTON_STEPS):
        y -= (y*y-x*x*x+17*x)/(2*y)
    curve_check((x, y))
    assert mul(17, (x, y)) is None
    return x, y


# q^2-Frobenius is [-q]; q^32 therefore contains E[f].
group_order=(P**16-1)**2
assert group_order%17**2==0 and group_order%17**3!=0
ii=FF(-1).sqrt()
assert ii*ii==-1
for seed in range(1,100):
    x=FF.gen()+seed
    rhs=x**3-17*x
    if not rhs.is_square():
        continue
    A17=mul(group_order//17**2,(x,rhs.sqrt()))
    if A17 is None:
        continue
    assert mul(17,A17) is None
    if add(mul(4,A17),cm_i(A17,ii)) is None:
        continue
    if add(mul(4,A17),neg(cm_i(A17,ii))) is None:
        continue
    break
else:
    raise AssertionError("no primitive seed")
fourth_root=FF(17).sqrt().sqrt()
assert fourth_root**4==17
Q0=(ii*fourth_root**2,(1-ii)*fourth_root**3)
assert mul(2,Q0)==(FF(0),FF(0))
for A in (A17,Q0):
    assert (A[0]**(P*P),A[1]**(P*P))==mul(-P,A)
i=ring_lift(ii)
for _ in range(NEWTON_STEPS):
    i-=(i*i+1)/(2*i)
assert i*i==-1
a=ring_lift(fourth_root)
for _ in range(NEWTON_STEPS):
    a-=(a**4-17)/(4*a**3)
assert a**4==17
Q=(i*a*a,(1-i)*a**3)
R17=lift_17_point(A17)
S=add(Q,R17)
assert mul(34,S)==(R(0),R(0))
assert mul(68,S) is None
S0=(*S,normalized_u(S))
orbit=[]
seen=set()
row=S0
for b in range(16):
    point=row
    for a in range(16):
        key=tuple(point[0].coeffs()+point[1].coeffs())
        assert key not in seen
        seen.add(key)
        if (a,b) in ((0,0),(3,7),(15,15)):
            assert point[2]==normalized_u(point[:2])
        orbit.append(point)
        point=gen_minus3(point)
    assert point==row
    row=gen_minus2_plus_i(row,i)
assert row==S0 and len(orbit)==256
assert sum((s[2] for s in orbit),R(0))==0

# Polynomial arithmetic in Z[U,X,Y]/(Y^2-X^3+17X).
# Keys are (degree_U, degree_X, degree_Y), with degree_Y in {0,1}.
def tidy(poly):
    return {key: value for key, value in poly.items() if value}


def derivation(poly):
    out = defaultdict(int)
    for (a, b, c), v in poly.items():
        if a:
            out[a-1, b+1, c] -= a*v
        if b:
            if c == 0:
                out[a, b-1, 1] += 2*b*v
            else:
                out[a, b+2, 0] += 2*b*v
                out[a, b, 0] -= 34*b*v
        if c:
            out[a, b+2, 0] += 3*v
            out[a, b, 0] -= 17*v
    return tidy(out)


C=[{(0,0,0):1}]
for n in range(MAX_M+1):
    new=defaultdict(int,derivation(C[-1]))
    for (a,b,c),v in C[-1].items():
        new[a+1,b,c]+=v
    C.append(tidy(new))

# Independently reconstruct w/sigma(w) from wp''=6wp^2-34.
num_q=(MAX_M+1)//4
wp=[Fraction(0)]
log_q=[Fraction(0)]
qq=[Fraction(1)]
for n in range(1,num_q+1):
    numerator=6*sum((wp[j]*wp[n-j] for j in range(1,n)),Fraction(0))
    if n==1:
        numerator-=34
    wp.append(numerator/Fraction((4*n-2)*(4*n-3)-12))
    log_q.append(wp[n]/Fraction(4*n*(4*n-1)))
    qq.append(sum((j*log_q[j]*qq[n-j] for j in range(1,n+1)),Fraction(0))/n)
q={4*n:v for n,v in enumerate(qq)}

@lru_cache(None)
def d_power(k,n):
    return C[k] if n==0 else derivation(d_power(k,n-1))

def int_vp(n):
    if n==0:
        return 10**9
    v=0
    while n%P==0:
        n//=P
        v+=1
    return v

polys=[]
for m in range(MAX_M+1):
    out=defaultdict(Fraction)
    for j,qj in q.items():
        if j>m+1:
            continue
        scale=qj/Fraction(factorial(m)*factorial(m+1-j))
        for key,v in d_power(m+1-j,m).items():
            out[key]+=scale*v
    out=tidy(out)
    loss=max([0]+[int_vp(v.denominator)-int_vp(v.numerator) for v in out.values()])
    assert loss<PREC
    scaled={k:v*P**loss for k,v in out.items()}
    assert all(v.denominator%P for v in scaled.values())
    modular={k:v.numerator*pow(v.denominator,-1,MOD)%MOD for k,v in scaled.items()}
    polys.append((loss,modular))

all_keys=set().union(*(poly.keys() for _,poly in polys))
max_u=max(a for a,b,c in all_keys)
max_x=max(b for a,b,c in all_keys)
powers=[]
for x,y,u in orbit:
    up,xp=[R(1)],[R(1)]
    for _ in range(max_u):up.append(up[-1]*u)
    for _ in range(max_x):xp.append(xp[-1]*x)
    powers.append((up,xp,y))

@lru_cache(None)
def trace_monomial(a,b,c):
    if c:
        return sum((up[a]*xp[b]*y for up,xp,y in powers),R(0))
    return sum((up[a]*xp[b] for up,xp,y in powers),R(0))

i_coeff=i.coeffs()
quad_index=next(j for j in range(1,DEG) if i_coeff[j]%P)
def quadratic_coefficients(value):
    coeff=value.coeffs()
    b=coeff[quad_index]*pow(i_coeff[quad_index],-1,MOD)%MOD
    a=(coeff[0]-b*i_coeff[0])%MOD
    assert value==a+b*i, "trace did not descend to K_q"
    return a,b

rows=[]
for m,(loss,poly) in enumerate(polys):
    value=sum((coeff*trace_monomial(*key) for key,coeff in poly.items()),R(0))
    a,b=quadratic_coefficients(value)
    t=min(int_vp(a),int_vp(b),PREC)
    exact=t<PREC
    rows.append({
      "m":m,"coefficient_denominator_loss":loss,
      "trace_scaled_coefficients_1_i":[a,b],
      "valuation":t-loss if exact else None,
      "valuation_lower_bound":t-loss,
      "leading_pair_mod_q":[(a//P**t)%P,(b//P**t)%P] if exact else None,
      "polynomial_terms":len(poly),
    })
first_nonintegral=next(
    (r for r in rows if r["valuation"] is not None and r["valuation"]<0),
    None)
r=(P+1)//4
Cmod=(-((-1)**r*comb(2*r,r)*17**r)*pow(2,-1,P))%P
first_layer_match=None
if MAX_M>=P+2:
    last=rows[P+2]
    assert last["coefficient_denominator_loss"]==2
    first_pair=rows[1]["trace_scaled_coefficients_1_i"]
    last_pair=last["trace_scaled_coefficients_1_i"]
    first_layer_match=all(
        (a-Cmod*Cmod*b)%P==0 for a,b in zip(last_pair,first_pair))
    assert first_layer_match
print(json.dumps({
 "prime":P,"ring_precision":PREC,"field_degree":DEG,
 "field_polynomial_low_to_high":FIELD_POLY,
 "seed":seed,"orbit_size":len(orbit),
 "no_CLS_calibration":True,
 "first_nonintegral_m":
     None if first_nonintegral is None else first_nonintegral["m"],
 "first_nonintegral_valuation":
     None if first_nonintegral is None else first_nonintegral["valuation"],
 "C_q_mod_q":Cmod,
 "q_squared_d_q_plus_2_equals_C_squared_d1_mod_q":first_layer_match,
 "rows":rows,
 "elapsed_seconds":round(time.monotonic()-START,3),
},indent=2))
