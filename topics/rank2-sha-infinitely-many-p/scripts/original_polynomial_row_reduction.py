def _determinant_of_hermite(H):
    assert H.nrows() == H.ncols() and H.is_hermite()
    value = H.base_ring().one()
    for i in range(H.nrows()):
        assert H[i, i] and H[i, i].leading_coefficient() == 1
        value *= H[i, i]
    return value


