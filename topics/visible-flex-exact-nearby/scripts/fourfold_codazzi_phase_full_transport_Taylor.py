"""Exact finite phase transport with a complete, unprojected residual.

The polynomial reference is generated by a projected Taylor recurrence;
every actual residual, including all frequencies outside that projection,
is then evaluated with Arb.  The true scalar model remainders, the mean,
both ray signs, and all original cubic interfaces are retained.  A prefix
report never claims a complete return/conjugacy certificate.
"""
