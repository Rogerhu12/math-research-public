def read(path):
    raw=Path(path).read_bytes()
    return json.loads(gzip.decompress(raw) if str(path).endswith('.gz') else raw)


def frac(x):return Fraction.from_float(float(x))


def mid(x):
    a,b=map(int,x.mid().man_exp())
    return Fraction(a*2**b) if b>=0 else Fraction(a,2**(-b))


def cplx(z):return acb(exact_arb(z[0]),exact_arb(z[1]))


def shift_scale(p,shift,scale):
    """Exact p(shift+scale*x), coefficients in increasing radial order."""
    return [sum((p[j]*math.comb(j,k)*shift**(j-k)*scale**k
                 for j in range(k,len(p))),Fraction(0)) for k in range(len(p))]


def scalar_mul(a,b):
    out=[Fraction(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):out[i+j]+=x*y
    return out


def radial_mul(a,b):
    out=[acb_poly([]) for _ in range(len(a)+len(b)-1)]
    for i,x in enumerate(a):
        for j,y in enumerate(b):out[i+j]+=x*y
    return out


def scalar_times(a,b):
    out=[acb_poly([]) for _ in range(len(a)+len(b)-1)]
    for i,x in enumerate(a):
        z=exact_arb(x)
        for j,y in enumerate(b):out[i+j]+=y*z
    return out


def radial_add(a,b):
    return [(a[j] if j<len(a) else acb_poly([]))+
            (b[j] if j<len(b) else acb_poly([])) for j in range(max(len(a),len(b)))]


def angular_derivative(p,N):
    return acb_poly([p[j]*acb(0,4*(j-N)) for j in range(2*N+1)])


def angular_norm(p,N,width,cutoff=None,outside=False):
    total=arb(0)
    key=(N,ctx.prec,width.str())
    if key not in NORM_WEIGHTS:
        NORM_WEIGHTS[key]=[(4*k*width).exp() for k in range(N+1)]
    weights=NORM_WEIGHTS[key]
    for j in range(2*N+1):
        k=abs(j-N)
        if cutoff is not None and ((k>cutoff)!=outside):continue
        total+=abs(p[j])*weights[k]
    return total.upper()


def radial_angular_sup(a,N,width):
    return sum((angular_norm(p,N,width) for p in a),arb(0)).upper()


def exact_real_midpoint(p,N):
    """Define a real trigonometric polynomial by explicit dyadic midpoints.

    Negative coefficients are defined by conjugation, not assumed equal
    to separately rounded Arb evaluations.  The later full residual pays
    every resulting rounding difference.
    """
    out=[(Fraction(0),Fraction(0)) for _ in range(2*N+1)]
    out[N]=(mid(p[N].real),Fraction(0))
    for j in range(1,N+1):
        re,im=mid(p[N+j].real),mid(p[N+j].imag)
        out[N+j]=(re,im);out[N-j]=(re,-im)
    return out


def encode(state):return [[[str(re),str(im)] for re,im in side] for side in state]


def initial_state(root,N):
    state=[(Fraction(0),Fraction(0)) for _ in range(2*N+1)]
    a=list(map(Fraction,root['exact_H_sine_coefficients']))
    b=list(map(Fraction,root['exact_H_cosine_coefficients']))
    for j,(s,c) in enumerate(zip(a,b),1):
        state[N+j]=(c/2,-s/2);state[N-j]=(c/2,s/2)
    return [list(state),list(state)]


class Fields:
    def __init__(self,saved,alpha,nodes,offsets,width):
        self.saved=saved;self.alpha=alpha;self.nodes=nodes;self.offsets=offsets;self.width=width

    def at(self,row,piece,left,right):
        h=right-left;scalars={}
        for name,item in row['models'].items():
            scalars[name]=shift_scale(list(map(Fraction,item['exact_centered_polynomial'])),
                                     left-Fraction(row['center']),h)
        state=[]
        for k in range(65):
            p=[self.alpha*frac(x) for x in self.saved['piece_coefficients'][::-1,piece,k]]
            p=shift_scale(p,left-self.nodes[piece],h);p[0]+=self.offsets[piece][k];state.append(p)
        u=[];v=[]
        for radial in range(8):
            ur=[acb(0) for _ in range(65)];vr=[acb(0) for _ in range(65)]
            for j in range(1,33):
                uj=state[j-1][radial] if radial<4 else Fraction(0)
                vj=state[32+j][radial] if radial<4 else Fraction(0)
                ur[32+j]=acb(0,exact_arb(-uj/2));ur[32-j]=acb(0,exact_arb(uj/2))
                vr[32+j]=vr[32-j]=acb(exact_arb(vj/2))
            vr[32]=acb(exact_arb(scalars['s'][radial]+(state[32][radial] if radial<4 else 0)))
            if radial<4:u.append(acb_poly(ur))
            v.append(acb_poly(vr))
        S=radial_add(radial_mul(u,u),scalar_times(scalars['K'],radial_mul(v,v)))
        drift=scalar_times(scalars['beta'],S)
        for k,p in enumerate(drift):
            drift[k]=acb_poly([p[j]*acb(0,exact_arb(Fraction(-1,4*(j-MF))))
                              if j!=MF else acb(0) for j in range(2*MF+1)])
        mean=list(scalars['s'])
        for j in range(4):mean[j]+=state[32][j]
        speed=[-z for z in scalar_mul(scalar_mul(scalars['gamma'],mean),scalars['q'])]
        field=[]
        for sign in (1,-1):
            one=[]
            for k,p in enumerate(drift):
                values=[p[j]*exact_arb(h) for j in range(2*MF+1)]
                if k<len(speed):values[MF]+=exact_arb(sign*h*speed[k])
                one.append(acb_poly(values))
            field.append(one)
        # Uniform complete scalar errors are reused only as value errors.
        # No differentiation of a uniform value remainder is performed.
        eps={n:box_from_record(z['complete_uniform_remainder']).upper() for n,z in row['models'].items()}
        true={n:abs(box_from_record(z['complete_true_value'])).upper() for n,z in row['models'].items()}
        U=radial_angular_sup(u,32,self.width);V=radial_angular_sup(v,32,self.width)
        Km=sum((abs(exact_arb(z)) for z in scalars['K']),arb(0)).upper()
        qm=sum((abs(exact_arb(z)) for z in scalars['q']),arb(0)).upper()
        mm=sum((abs(exact_arb(z)) for z in mean),arb(0)).upper()
        drift_error=(eps['beta']*(U*U+Km*V*V)/4+
            true['beta']*(eps['K']*V*V+true['K']*eps['s']*(2*V+eps['s']))/4).upper()
        speed_error=(eps['gamma']*mm*qm+
            true['gamma']*(eps['s']*qm+(mm+eps['s'])*eps['q'])).upper()
        return field,(drift_error+speed_error).upper(),dict(
            model_U_strip_norm=record(U),model_V_strip_norm=record(V),
            complete_drift_model_error=record(drift_error),complete_mean_speed_model_error=record(speed_error))


def one_step(fields,state,degree,width,h):
    endpoints=[];fees=[];polynomial_digest=hashlib.sha256()
    for F,start in zip(fields,state):
        N=(len(start)-1)//2;exact=[list(start)]
        W=[acb_poly(list(map(cplx,start)))];dW=[angular_derivative(W[0],N)]
        for n in range(degree):
            rhs=F[n].left_shift(N) if n<len(F) else acb_poly([])
            for i in range(min(n,len(F)-1)+1):rhs+=F[i]*dW[n-i]
            candidate=acb_poly([-rhs[MF+j]/(n+1) for j in range(2*N+1)])
            coeff=exact_real_midpoint(candidate,N);exact.append(coeff)
            W.append(acb_poly(list(map(cplx,coeff))));dW.append(angular_derivative(W[-1],N))
        residual=radial_mul(F,dW)
        for n,p in enumerate(F):residual[n]+=p.left_shift(N)
        for n in range(degree):residual[n]+=(W[n+1]*(n+1)).left_shift(MF)
        retained=arb(0);outside=arb(0)
        for n,p in enumerate(residual):
            retained+=angular_norm(p,N+MF,width,N,False)/(n+1)
            outside+=angular_norm(p,N+MF,width,N,True)/(n+1)
        derivative_integral=1+sum((angular_norm(p,N,width)/(n+1) for n,p in enumerate(dW)),arb(0))
        endpoint=[(sum((z[j][0] for z in exact),Fraction(0)),sum((z[j][1] for z in exact),Fraction(0)))
                  for j in range(2*N+1)]
        endpoints.append(endpoint)
        for p in exact:
            polynomial_digest.update((json.dumps([[str(a),str(b)] for a,b in p],separators=(',',':'))+'\n').encode())
        fees.append(dict(retained=retained.upper(),outside=outside.upper(),derivative_integral=derivative_integral.upper()))
    return endpoints,fees,polynomial_digest.hexdigest()


def scalar_inputs(paths,directory):
    candidates=list(paths)
    for path in directory:
        candidates+=sorted(path.glob('**/germ[0-9][0-9][0-9][0-9].json.gz'))
    by_index={}
    for path in candidates:
        doc=read(path);cfg=doc.get('configuration',{})
        if (doc.get('kind')!=KINDSCALAR or not doc.get('complete') or len(doc.get('gates',[]))!=6
            or not all(g['passed'] for g in doc['gates']) or cfg.get('source_sha256')!=SCALAR_SOURCE
            or cfg.get('provider_sha256')!=SCALAR_PROVIDER or cfg.get('exact_eta_offset')!='0'
            or cfg.get('jet_order')!=7):raise ValueError('a complete same-identity high7 scalar germ is required: '+str(path))
        index=doc['germ_index'];digest=sha(path)
        if index in by_index and by_index[index][2]!=digest:raise ValueError('duplicate scalar germ has a different native identity')
        by_index[index]=(path,doc,digest)
    indices=sorted(by_index)
    if not indices or indices!=list(range(indices[-1]+1)):
        raise ValueError('the requested complete scalar reports must be a gap-free prefix starting with reused germ zero')
    cfg=by_index[0][1]['configuration'];cursor=Fraction(0)
    for index in indices:
        path,doc,digest=by_index[index]
        if doc['configuration']!=cfg:raise ValueError('scalar configurations differ')
        a,b=map(Fraction,doc['exact_interval'])
        if a!=cursor or b<=a:raise ValueError('actual scalar germs overlap or leave a gap')
        sub=a
        for row in doc['rows']:
            x,y=map(Fraction,row['interval'])
            if x!=sub or y<=x:raise ValueError('actual accepted scalar cells leave a gap')
            sub=y
        if sub!=b:raise ValueError('a germ native omits part of its requested interval')
        cursor=b
    return by_index,cfg


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--candidate',type=Path,required=True)
    ap.add_argument('--root-contract',type=Path,default=Path('notes/2026-11-14-R133-final-phase-root-sliver-and-transport-contract-native.json.gz'))
    ap.add_argument('--scalar',type=Path,action='append',default=[])
    ap.add_argument('--scalar-dir',type=Path,action='append',default=[])
    ap.add_argument('--modes',type=int,default=64)
    ap.add_argument('--time-degree',type=int,default=12)
    ap.add_argument('--bits',type=int,default=256)
    ap.add_argument('--retained-residual-density',type=Fraction,default=Fraction(1,10**18))
    ap.add_argument('--max-depth',type=int,default=20)
    ap.add_argument('--resume',action='store_true')
    ap.add_argument('--out-dir',type=Path,required=True)
    args=ap.parse_args();started=time.monotonic();ctx.prec=args.bits
    if args.out_dir.exists() and not args.resume:raise FileExistsError('keep every actual phase transport attempt')
    args.out_dir.mkdir(parents=True,exist_ok=True)
    if sha(args.candidate)!=CANDIDATE or sha(args.root_contract)!=ROOT_REPORT:
        raise ValueError('the same actual repaired centre and root contract are required')
    if not 32<=args.modes<=192 or not 8<=args.time_degree<=24 or args.bits<192:
        raise ValueError('invalid explicitly bounded complete phase polynomial parameters')
    reports,cfg=scalar_inputs(args.scalar,args.scalar_dir);root=read(args.root_contract)
    if not root['complete'] or root['derived_definition_sha256']!=REPAIR:raise ValueError('the complete root contract is unavailable')
    saved=load_candidate(args.candidate);meta=json.loads(str(saved['metadata']))
    if cfg['exact_nu']!=meta['exact_float_nu'] or cfg['complete_requested_interval'][1]!=root['exact_scalar_stop']:
        raise ValueError('the true parameter/root stop differs from the installed contract')
    alpha=Fraction(meta['exact_float_amplitude']);nodes=list(map(frac,saved['radial_nodes']))
    endpoint=Fraction(reports[max(reports)][1]['exact_interval'][1]);offsets={}
    for piece,offset,jump in iter_repair(saved,alpha):
        if nodes[piece]>=endpoint:break
        offsets[piece]=offset
    width=exact_arb(Fraction(root['residual_and_terminal_Fourier_strip']))
    fields=Fields(saved,alpha,nodes,offsets,width);state=initial_state(root,args.modes)
    cursor=Fraction(0);piece=0;rows=[];rejected=[];total_finite=arb(0);total_model=arb(0);total_outside=arb(0)
    config=dict(kind='actual_complete_projected_phase_polynomial_with_full_residual_v1',
        source_sha256=sha(__file__),candidate_sha256=CANDIDATE,derived_definition_sha256=REPAIR,
        root_contract_sha256=ROOT_REPORT,scalar_configuration=cfg,modes=args.modes,time_degree=args.time_degree,
        bits=args.bits,residual_strip=root['residual_and_terminal_Fourier_strip'],
        exact_retained_residual_density=str(args.retained_residual_density),max_depth=args.max_depth,
        exact_eta_offset='0',whole_original_eta=False,full_output_frequency_bound=args.modes+MF,
        exact_initial_H_sine_coefficients=root['exact_H_sine_coefficients'],
        exact_initial_H_cosine_coefficients=root['exact_H_cosine_coefficients'])
    last_completed=-1
    for checkpoint in sorted(args.out_dir.glob('transport-germ[0-9][0-9][0-9][0-9].json.gz')):
        old=read(checkpoint);index=old.get('last_complete_germ')
        if (not args.resume or old.get('configuration')!=config or not old.get('complete_requested_prefix')
            or index!=last_completed+1 or index not in reports):
            raise ValueError('resume requires the exact complete chronological source/input prefix')
        if any(r['germ_index']!=index or r['scalar_native_sha256']!=reports[index][2] for r in old['rows']):
            raise ValueError('a completed transport germ used different actual scalar input bytes')
        if Fraction(old['last_exact_radial_point'])!=Fraction(reports[index][1]['exact_interval'][1]):
            raise ValueError('a completed transport germ ends at a different radial point')
        rows+=old['rows'];rejected+=old['rejected_cells'];last_completed=index
        state=[[(Fraction(a),Fraction(b)) for a,b in side] for side in old['exact_phase_state']]
        cursor=Fraction(old['last_exact_radial_point'])
        total_finite=box_from_record(old['integrated_retained_finite_residual']).upper()
        total_outside=box_from_record(old['integrated_all_unretained_frequencies_residual']).upper()
        total_model=box_from_record(old['integrated_complete_scalar_model_residual']).upper()
    for index,(path,doc,digest) in sorted(reports.items()):
        if index<=last_completed:continue
        first_row=len(rows)
        for scalar_row in doc['rows']:
            a,b=map(Fraction,scalar_row['interval'])
            while a<b:
                while nodes[piece+1]<=a:piece+=1
                right=min(b,nodes[piece+1]);pending=[(a,right,0)]
                while pending:
                    left,end,depth=pending.pop()
                    if left!=cursor:raise ArithmeticError('the chronological transport prefix is not continuous')
                    F,model_error,field_info=fields.at(scalar_row,piece,left,end)
                    next_state,fees,polysha=one_step(F,state,args.time_degree,width,end-left)
                    retained=sum((z['retained'] for z in fees),arb(0)).upper()
                    if not retained<exact_arb((end-left)*args.retained_residual_density):
                        rejected.append(dict(interval=list(map(str,(left,end))),germ_index=index,piece=piece,depth=depth,
                            actual_retained_finite_residual=record(retained)))
                        if depth>=args.max_depth:
                            save(args.out_dir/'failed-prefix.json.gz',dict(configuration=config,complete=False,
                                last_exact_radial_point=str(cursor),exact_phase_state=encode(state),rows=rows,rejected=rejected,
                                actual_failure='maximum retained-polynomial residual subdivision reached'))
                            raise RuntimeError('the complete retained polynomial residual did not fit the explicit budget')
                        midp=(left+end)/2;pending.extend(((midp,end,depth+1),(left,midp,depth+1)));continue
                    outside=sum((z['outside'] for z in fees),arb(0)).upper()
                    model=(exact_arb(end-left)*model_error*sum((z['derivative_integral'] for z in fees),arb(0))).upper()
                    total_finite+=retained;total_outside+=outside;total_model+=model
                    rows.append(dict(germ_index=index,scalar_native_sha256=digest,actual_candidate_piece=piece,
                        interval=list(map(str,(left,end))),depth=depth,polynomial_sha256=polysha,
                        complete_retained_finite_residual=record(retained),complete_unretained_finite_residual=record(outside),
                        complete_true_scalar_model_residual=record(model),
                        complete_true_residual=record((retained+outside+model).upper()),
                        both_derivative_integrals=[record(z['derivative_integral']) for z in fees],
                        exact_initial_value_shared_with_previous_endpoint=True,**field_info))
                    state=next_state;cursor=end
                    if len(rows)%64==0:
                        print(dict(actual_steps=len(rows),germ=index,radial_point=str(cursor),
                            retained=total_finite.str(10),unretained=total_outside.str(10),
                            scalar=total_model.str(10),seconds=time.monotonic()-started),flush=True)
                a=right
        snapshot=dict(configuration=config,complete_requested_prefix=True,whole_negative_domain=False,
            last_complete_germ=index,last_exact_radial_point=str(cursor),exact_phase_state=encode(state),
            integrated_retained_finite_residual=record(total_finite.upper()),
            integrated_all_unretained_frequencies_residual=record(total_outside.upper()),
            integrated_complete_scalar_model_residual=record(total_model.upper()),
            exact_all_polynomial_value_jumps='0',exact_initial_polynomial_error='0',
            rows=rows[first_row:],rejected_cells=[r for r in rejected if r['germ_index']==index],
            no_whole_return_or_conjugacy_claimed=True,seconds=time.monotonic()-started)
        save(args.out_dir/f'transport-germ{index:04d}.json.gz',snapshot)
        print(dict(germ=index,actual_steps=len(rows),retained=total_finite.str(10),
                   unretained=total_outside.str(10),scalar=total_model.str(10),seconds=time.monotonic()-started),flush=True)
    whole=len(reports)==cfg['total_germs'] and cursor==Fraction(root['exact_scalar_stop'])
    difference=acb_poly([cplx((state[1][j][0]-state[0][j][0],state[1][j][1]-state[0][j][1]))
                         for j in range(2*args.modes+1)])
    difference[args.modes]-=exact_arb(Fraction(root['exact_proposed_rotation']))
    terminal=angular_norm(difference,args.modes,width)
    defect=(terminal+total_finite+total_outside+total_model+
            box_from_record(root['full_two_ray_conjugacy_defect_sliver'])).upper() if whole else None
    report=dict(configuration=config,complete_requested_prefix=True,whole_negative_domain=whole,
        exact_processed_interval=['0',str(cursor)],processed_germs=len(reports),actual_steps=len(rows),
        exact_phase_state=encode(state),scalar_inputs={str(p):d for p,doc,d in reports.values()},
        integrated_retained_finite_residual=record(total_finite.upper()),
        integrated_all_unretained_frequencies_residual=record(total_outside.upper()),
        integrated_complete_scalar_model_residual=record(total_model.upper()),
        integrated_complete_true_transport_residual=record((total_finite+total_outside+total_model).upper()),
        exact_all_polynomial_value_jumps='0',exact_initial_polynomial_error='0',
        complete_terminal_defect_norm=record(terminal),
        complete_actual_conjugacy_defect_upper=None if defect is None else record(defect),
        conjugacy_itself_not_claimed=True,no_parameter_or_global_inverse_claimed=True,
        all_projected_reference_frequencies_outside_projection_retained_in_residual=True,
        full_even_mean_and_both_branches_retained=True,rejected_cells=rejected,
        seconds=time.monotonic()-started)
    save(args.out_dir/'report.json.gz',report)
    print(dict(complete_requested_prefix=True,whole_negative_domain=whole,steps=len(rows),
        complete_transport_residual=(total_finite+total_outside+total_model).str(16),
        terminal=terminal.str(16),seconds=report['seconds']),flush=True)


if __name__=='__main__':main()
