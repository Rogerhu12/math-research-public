#!/usr/bin/env python3
"""Exact actual same-cone chronological density phases and their tame windows.

Every diagonal phase is generated by its true real coefficient, hence unitary
in the balanced base space.  The physical common mean is separated exactly.
All cross branches, opposite cones, cutoff edges, heads and means remain
explicit external terms in this result; no full return inverse is claimed.
"""
from __future__ import annotations
import argparse,math,time
from fractions import Fraction
from pathlib import Path
from flint import arb,ctx
from fourfold_phase_beta_bulk_interval import exact_arb
from fourfold_phase_root_fourier_fit import save,sha,stored
from fourfold_negative_collar_root_fourier_budget import record
from fourfold_negative_canonical_cancellation_chart import checked
from fourfold_actual_high_density_first_phase import derivative_multiplier
from fourfold_actual_relative_ray_real_jets import bell_table,complete_comparisons
from fourfold_negative_root_physical_graph_operator import mult


def up(v):return stored(v).upper()
def lo(v):return stored(v).lower()


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--high',type=Path,default=Path('notes/2026-11-13-actual-fixed-label-high-density-Volterra.json'))
    p.add_argument('--jets',type=Path,default=Path('notes/2026-11-13-R106-full-relative-real-log-jets.json.gz'))
    p.add_argument('--scales',type=int,nargs='+',default=[1,4096,65536,1048576,2**30,2**40])
    p.add_argument('--bits',type=int,default=320)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    if a.out.exists() or min(a.scales)<1:raise ValueError('a fresh exact phase report and positive scales required')
    ctx.prec=a.bits;tick=time.monotonic()
    h=checked(a.high,'fourfold_actual_label_high_density_volterra.py')
    j=checked(a.jets,'fourfold_actual_relative_ray_log_jets.py')
    if (h['identity']!=j['identity'] or not j['all_pairs_of_strict_times_and_both_directions']
        or not j['entire_original_real_parameter_box']):
        raise ValueError('the same actual full characteristic family is required')
    oldpath=Path(j['original_complete_higher_jet_report'])
    old=checked(oldpath,'fourfold_actual_relative_ray_real_jets.py')
    if old['inputs'].get(str(a.high))!=sha(a.high):
        raise ValueError('the actual real jets use another complete density equation')
    Cr=up(j['accepted_relative_first_derivative'])
    H=[arb(0),Cr]+[up(z['accepted_complete_relative_derivative'])
                   for z in j['accepted_real_derivative_bounds']]
    if [z['order'] for z in j['accepted_real_derivative_bounds']]!=[2,3,4]:
        raise ValueError('the full four real derivatives are required')
    sf=lo(h['normalized_field_strip']);Q=up(h['complete_integrated_density_kappa'])
    Mm=up(h['full_m_modulus']);Msqrtmu=up(h['full_sqrt_mu_modulus']);MT=up(h['full_T_modulus'])
    B=bell_table(H,3)
    # a_sigma=H_sigma'*(kappa o H_sigma). All derivatives are in x=4theta.
    # The complete analytic field bound supplies kappa^(l) <= l! M_kappa/sf^l;
    # every actual real flow derivative comes from the same-label certificate.
    coefficient=[]
    for n in range(4):
        coefficient.append(sum((math.comb(n,k)*H[k+1]*
            sum((B[n-k][l]*math.factorial(l)/sf**l for l in range(n-k+1)),arb(0))
            for k in range(n+1)),arb(0)).upper())
    rows=[]
    for N in a.scales:
        multipliers=[derivative_multiplier(N,n,coefficient) for n in range(4)]
        gain=[None]+[(arb(2).sqrt()*Q*(multipliers[n-1]*multipliers[n]).sqrt()/(8*N)).upper()
                     for n in range(1,4)]
        phase=(Cr*Q/(8*N)).upper()
        G=[arb(1)]
        for n in range(1,4):G.append((1+gain[n]*G[-1]).upper())
        fractional={}
        for s in (Fraction(1,2),Fraction(4,3),Fraction(3,2),Fraction(5,2)):
            n=s.numerator//s.denominator;t=s-n
            fractional[str(s)]=record((G[n]**exact_arb(1-t)*G[n+1]**exact_arb(t)).upper())
        r0=min((phase*phase/2).upper(),(2+phase).upper())
        r2=(gain[1]*gain[2]/2).upper()
        r43=(r0**(arb(1)/3)*r2**(arb(2)/3)).upper()
        ps,ds=complete_comparisons(N,Cr,H,3)
        source=[];low=[]
        for n in range(4):
            source.append((G[n]*ds[n]*mult(N,n,Mm,sf)/(2*arb(N)).sqrt()).upper())
            low.append((G[n]*ds[n]*mult(N,n,arb(1),sf)*Q/(2*arb(N)).sqrt()).upper())
        Gh=(G[1].sqrt()).upper()
        height=(Mm*Cr.sqrt()/(2*(2*arb(N)).sqrt())).upper()
        raw=(arb(N).sqrt()*Gh).upper()
        flux=(Msqrtmu*(2*Cr*arb(N)).sqrt()*Gh+MT*height).upper()
        rows.append(dict(scale=N,
            exact_balanced_base_phase_and_inverse=record(arb(1)),
            complete_actual_phase_integrated_base_generator=record(phase),
            full_real_coefficient_multiplier_integrals=[record((Q*z).upper()) for z in multipliers],
            complete_one_order_generator_integrals=[record(gain[n]) for n in range(1,4)],
            chronological_phase_and_inverse_integer_windows=[record(z) for z in G],
            chronological_phase_and_inverse_fractional_windows=fractional,
            chronological_minus_identity_minus_actual_first_phase_base=record(r0),
            chronological_minus_identity_minus_actual_first_phase_both_two_order_windows=record(r2),
            chronological_minus_identity_minus_actual_first_phase_both_four_thirds_windows=record(r43),
            frozen_exponential_has_the_same_window_bounds=True,
            chronological_minus_frozen_phase_both_two_order_windows=record((2*r2).upper()),
            hard_cutoff_commutator_edge_is_retained=True,
            gauged_complete_ordinary_source_integer_windows=[record(z) for z in source],
            gauged_complete_low_height_history_integer_windows=[record(z) for z in low],
            physical_high_height_from_balanced_L2=record(height),
            physical_raw_density_from_balanced_HNhalf=record(raw),
            physical_high_momentum_from_balanced_HNhalf=record(flux)))
    n0=next((z for z in rows if z['scale']==2**20),None)
    gates=[]
    def gate(name,ok):
        gates.append(dict(name=name,passed=bool(ok)))
        if not ok:raise ValueError(name)
    gate('same physical density coefficient rather than native curvature kappa',
         h['density_kappa_definition'].startswith('Fcal/mu'))
    gate('complete field cover and all true real times retained',
         h['positive_cells']==215 and j['all_550_true_segments_and_4400_exact_controls'])
    gate('full mean and head locations are unchanged',
         h['low_to_high_high_to_low_and_mean_paths_retained']
         and j['every_head_mean_source_and_reconstruction_position_unchanged'])
    if n0 is not None:
        gate('actual high phase has a small finite third Sobolev comparison',
             up(n0['chronological_phase_and_inverse_integer_windows'][3])<2)
    out=dict(kind='actual_same_cone_exact_unitary_density_phase_common_mean_and_tame_windows',
        complete=True,proved=True,source_sha256=sha(__file__),bits=a.bits,
        identity=h['identity'],inputs={str(p):sha(p) for p in (a.high,a.jets,oldpath)},
        entire_original_real_parameter_box=True,native_geometry_recomputed=0,
        exact_physical_interval=h['exact_physical_interval'],
        balanced_variable='Z_sigma=|D|^-1/2 P_H X_sigma; D=-i partial_x, x=4theta',
        exact_same_cone_generator='i*sigma*epsilon/8 * |D|^-1/2 P_epsilon,N M_(Hsigma_prime*(kappa o Hsigma)) P_epsilon,N |D|^-1/2',
        exact_common_mean_identity='mean(Hsigma_prime*(kappa o Hsigma))=mean(kappa), independently of sigma',
        exact_common_mean_phase='exp(i*sigma*epsilon/8 * |D|^-1 * integral mean(kappa) dr)',
        radial_scalar_mean_phase_is_unitary_in_every_Sobolev_window=True,
        real_nonmean_chronological_phase_kept_exactly=True,
        exact_first_phase='sigma/8*integral Hsigma_prime*(kappa o Hsigma) dr, the original full true phase function',
        full_off_diagonal_generator='|D|^-1/2 K_HH |D|^1/2 minus the four same-branch same-sign generators, with original PH locations',
        exact_gauged_equation='W_prime=U_diag^* G_off U_diag W+U_diag^* |D|^-1/2 F_H',
        physical_source_units=h['ordinary_source_scope'],
        source_budget_scope='Norm of the exact gauged forcing, not the solution of the remaining off-diagonal/head/mean time problem.',
        complete_low_history=h['full_low_head'],
        exact_low_mean_rows=dict(alpha=h['exact_flux_mean_row'],c=h['exact_height_mean_row'],
            nonzero_head=h['exact_nonzero_head_row']),
        exact_physical_reconstruction=h['exact_physical_reconstruction'],
        hard_cutoff_commutator_identity='[PAP,PBP]=P[A,B]P-PALBP+PBLAP, L=Pi_epsilon-P',
        hard_cutoff_edge_counterexample='a=2cos(x), b=2sin(x): <e_N,[A_N(a),A_N(b)]e_N>=-2i/(N(N+1)); hence no uniform order-three claim after hard projection',
        no_cutoff_edge_or_mean_path_discarded=True,
        complete_integrated_true_density=record(Q),
        complete_real_coefficient_derivative_factors=[record(z) for z in coefficient],
        rows=rows,gates=gates,
        exact_same_cone_phase_reduction_proved=True,
        full_coupled_negative_propagator_improved=False,
        full_returned_Rstar_improved=False,finite_head_feedback_solved=False,
        full_feedback_inverse_proved=False,new_complex_width_permission=False,
        dependencies={name:sha(Path(__file__).with_name(name)) for name in (
            'fourfold_phase_beta_bulk_interval.py','fourfold_phase_root_fourier_fit.py',
            'fourfold_negative_collar_root_fourier_budget.py','fourfold_negative_canonical_cancellation_chart.py',
            'fourfold_actual_high_density_first_phase.py','fourfold_actual_relative_ray_real_jets.py',
            'fourfold_negative_root_physical_graph_operator.py')},
        seconds=time.monotonic()-tick)
    save(a.out,out)
    print(dict(complete=True,scale2power20=n0,out=str(a.out),sha256=sha(a.out)),flush=True)


if __name__=='__main__':main()

