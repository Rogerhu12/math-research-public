class Fp2:
    def __init__(self,q):
        self.q=q
        self.zero=(0,0)
        self.one=(1,0)
        self.i=(0,1)
    def add(self,a,b):return ((a[0]+b[0])%self.q,(a[1]+b[1])%self.q)
    def neg(self,a):return ((-a[0])%self.q,(-a[1])%self.q)
    def sub(self,a,b):return self.add(a,self.neg(b))
    def scale(self,a,n):return (a[0]*n%self.q,a[1]*n%self.q)
    def mul(self,a,b):return ((a[0]*b[0]-a[1]*b[1])%self.q,(a[0]*b[1]+a[1]*b[0])%self.q)
    def inv(self,a):
        d=pow((a[0]*a[0]+a[1]*a[1])%self.q,-1,self.q)
        return (a[0]*d%self.q,-a[1]*d%self.q)
    def div(self,a,b):return self.mul(a,self.inv(b))
    def power(self,a,n):
        out=self.one
        while n:
            if n&1:out=self.mul(out,a)
            a=self.mul(a,a);n//=2
        return out


class EC:
    def __init__(self,F,a,b):self.F,self.a,self.b=F,a,b
    def on(self,P):
        if P is None:return True
        F=self.F;x,y=P
        return F.mul(y,y)==F.add(F.add(F.mul(F.mul(x,x),x),F.mul(self.a,x)),self.b)
    def neg(self,P):return None if P is None else (P[0],self.F.neg(P[1]))
    def add(self,P,Q):
        if P is None:return Q
        if Q is None:return P
        F=self.F
        if P[0]==Q[0]:
            if F.add(P[1],Q[1])==F.zero:return None
            slope=F.div(F.add(F.scale(F.mul(P[0],P[0]),3),self.a),F.scale(P[1],2))
        else:slope=F.div(F.sub(Q[1],P[1]),F.sub(Q[0],P[0]))
        x=F.sub(F.sub(F.mul(slope,slope),P[0]),Q[0])
        y=F.sub(F.mul(slope,F.sub(P[0],x)),P[1])
        return (x,y)
    def mult(self,P,n):
        if n<0:return self.mult(self.neg(P),-n)
        R=None
        while n:
            if n&1:R=self.add(R,P)
            P=self.add(P,P);n//=2
        return R
    def velu43(self,P):
        F=self.F;R=P;rows=[];t_sum=F.zero;w_sum=F.zero
        for _ in range(21):
            assert R is not None and self.on(R)
            u,y=R;t=F.add(F.scale(F.mul(u,u),6),F.scale(self.a,2));v=F.scale(F.mul(y,y),4)
            rows.append((u,t,v));t_sum=F.add(t_sum,t);w_sum=F.add(w_sum,F.add(v,F.mul(u,t)))
            R=self.add(R,P)
        target=EC(F,F.sub(self.a,F.scale(t_sum,5)),F.sub(self.b,F.scale(w_sum,7)))
        def phi(Q):
            x,y=Q;xx=x;factor=F.one
            for u,t,v in rows:
                d=F.inv(F.sub(x,u));d2=F.mul(d,d)
                xx=F.add(xx,F.add(F.mul(t,d),F.mul(v,d2)))
                factor=F.sub(factor,F.add(F.mul(t,d2),F.scale(F.mul(v,F.mul(d2,d)),2)))
            out=(xx,F.mul(y,factor));assert target.on(out)
            return out
        return target,phi
    def miller(self,P,Q,n):
        F=self.F;R=P;value=F.one
        def line(U,V):
            if U[0]==V[0] and F.add(U[1],V[1])==F.zero:return F.sub(Q[0],U[0])
            if U[0]==V[0]:slope=F.div(F.add(F.scale(F.mul(U[0],U[0]),3),self.a),F.scale(U[1],2))
            else:slope=F.div(F.sub(V[1],U[1]),F.sub(V[0],U[0]))
            W=self.add(U,V);num=F.sub(F.sub(Q[1],U[1]),F.mul(slope,F.sub(Q[0],U[0])))
            return num if W is None else F.div(num,F.sub(Q[0],W[0]))
        for bit in bin(n)[3:]:
            value=F.mul(F.mul(value,value),line(R,R));R=self.add(R,R)
            if bit=='1':value=F.mul(value,line(R,P));R=self.add(R,P)
        assert R is None
        return value


class Field44:
    def __init__(self,f):
        assert len(f)==45 and f[-1]==1
        self.f=f;self.n=44
        self.zero=tuple([(0,0)]*44)+(1,)
        self.one=self.scalar(1)
        self.z=tuple([(0,0),(1,0)]+[(0,0)]*42)+(1,)
    def scalar(self,a):return tuple([(a,0)]+[(0,0)]*43)+(1,)
    def normalize(self,a,d):
        g=math.gcd(d,*[v for pair in a for v in pair])
        if d<0:g=-g
        return tuple([(x//g,y//g) for x,y in a])+(d//g,)
    def add(self,a,b):
        g=math.gcd(a[-1],b[-1]);u=b[-1]//g;v=a[-1]//g
        return self.normalize([(u*x+v*y,u*xx+v*yy) for (x,xx),(y,yy) in zip(a[:-1],b[:-1])],a[-1]*u)
    def sub(self,a,b):return self.add(a,tuple([(-x,-y) for x,y in b[:-1]])+(b[-1],))
    def conj(self,a):return tuple([(x,-y) for x,y in a[:-1]])+(a[-1],)
    def mul(self,a,b):
        out=[[0,0] for _ in range(87)]
        for j,(u,v) in enumerate(a[:-1]):
            if u==v==0:continue
            for k,(x,y) in enumerate(b[:-1]):
                if x==y==0:continue
                out[j+k][0]+=u*x-v*y;out[j+k][1]+=u*y+v*x
        for j in range(86,43,-1):
            u,v=out[j]
            if u==v==0:continue
            for k,c in enumerate(self.f[:-1]):
                out[j-44+k][0]-=c*u;out[j-44+k][1]-=c*v
        return self.normalize(out[:44],a[-1]*b[-1])
    def power(self,a,n):
        assert n>=0
        r=self.one
        while n:
            if n&1:r=self.mul(r,a)
            n//=2
            if n:a=self.mul(a,a)
        return r
    def evaluate(self,coeff,a):
        r=self.zero
        for c in reversed(coeff):r=self.add(self.mul(r,a),self.scalar(c))
        return r
    def compose(self,b,a):
        r=self.zero
        for x,y in reversed(b[:-1]):
            r=self.mul(r,a)
            coeff=list(r[:-1]);coeff[0]=(coeff[0][0]+r[-1]*x,coeff[0][1]+r[-1]*y)
            r=self.normalize(coeff,r[-1])
        return self.normalize(r[:-1],r[-1]*b[-1])


