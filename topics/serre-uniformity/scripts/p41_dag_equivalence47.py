#!/usr/bin/env python3
"""Bind the two generator versions after exact equality of all DAG data."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

FIELDS=['curve','order','modulus','indices','nodes','targets']


def read(path):
    raw=Path(path).read_bytes()
    return json.loads(gzip.decompress(raw) if str(path).endswith('.gz') else raw)


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def semantic_digest(data):
    obj={k:data[k] for k in FIELDS}
    return hashlib.sha256(json.dumps(obj,sort_keys=True,separators=(',',':')).encode()).hexdigest()


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--left',type=Path,required=True)
    ap.add_argument('--right',type=Path,required=True)
    ap.add_argument('--level',type=Path,required=True)
    ap.add_argument('--output',type=Path,required=True)
    args=ap.parse_args();left,right,level=map(read,[args.left,args.right,args.level])
    for field in FIELDS:assert left[field]==right[field],field
    assert level['complete'] and level['constant_dag_sha256']==sha(args.left)
    assert set(level['nodes'])==set(right['nodes'])
    for key,value in level['nodes'].items():assert value['degree']==right['nodes'][key]['degree']
    out={'scope':'Exact semantic equality of kernel DAGs generated by two source versions',
         'fields_compared':FIELDS,'node_count':len(left['nodes']),
         'all_kernel_coefficients_models_line_ids_parent_paths_targets_equal':True,
         'left_dag_sha256':sha(args.left),'right_dag_sha256':sha(args.right),
         'level_certificate_sha256':sha(args.level),
         'semantic_dag_sha256':semantic_digest(left),'source_sha256':sha(__file__)}
    args.output.write_text(json.dumps(out,sort_keys=True,indent=2)+'\n')
    print('equivalent',len(left['nodes']),'nodes',sha(args.output))


if __name__=='__main__':main()
