#!/usr/bin/env python3
"""Original R150 local projection at s=-6, with g-multiples retained.

Construct the SAME original 17 equations after the constant binomial shift.
The complete projection to pure/one-normal output is locally generated by
170 original pure-multiplier rows plus 54 g(s)-multiple coordinate rows.
The latter are justified using an actually nonzero coefficient of the original
pure quadratic vector; g itself is NEVER divided out.

Exact Taylor unit Schur on 224 x 155 (orders 0..4) measures the projected
cokernel length.  The paid full original length upper bound is 12 at s=-6.
Only if the actual projected length is 12 does the exact quotient sequence
prove all transverse-square outputs belong to the original LOCAL source image.
No new full Macaulay matrix, finite-field rank or normal form is computed.
"""
import argparse
import hashlib
import importlib.util
import json
from math import comb
from pathlib import Path
import resource
import signal
import time

from flint import fmpq, fmpq_mat

GENERATOR_SHA = "2757b900480fe3bf1450100188df1679801351f0330d609e1a39b9c7ca146186"
ACTIONS_SHA = "2ebf418575df39ca2ed0a2165a37e92071c415b4734969c5bedc64e0b9ef4332"
FORMAT = "r150-minus-six-original-projected-local-smith-v1"
BASE_POINT = -6
GENERIC_PROJECTION_RANK = 142
PAID_CONSTANT_FULL_RANK = 4345
PAID_FULL_LOCAL_LENGTH_UPPER = 12


def require(ok, message):
    if not ok:
        raise AssertionError(message)


def sha_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1048576), b""):
            h.update(chunk)
    return h.hexdigest()


def canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def module_at(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    obj = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(obj)
    return obj


def identity(n):
    return fmpq_mat([[int(i == j) for j in range(n)] for i in range(n)])


def binomial_translation(n, point):
    return fmpq_mat([[comb(i, j) * point ** (i-j) if j <= i else 0
                      for j in range(n)] for i in range(n)])


def rational_bit_record(value):
    q = fmpq(value)
    a, b = str(q).split("/") if "/" in str(q) else (str(q), "1")
    return {"numeratorBits": abs(int(a)).bit_length(),
            "denominatorBits": int(b).bit_length(),
            "sha256": hashlib.sha256(str(q).encode()).hexdigest()}


def coefficient_matrix(m, columns):
    return fmpq_mat([[column[i] for column in columns]
                     for i in range(len(columns[0]))])


def make_original_projection(m, j, order):
    """Original tensors, exact constant translation, then moving t=s+6."""
    K0 = fmpq_mat(m.ORIGINAL_K)
    B6 = binomial_translation(6, BASE_POINT)
    require(B6 * binomial_translation(6, -BASE_POINT) == identity(6),
            "Original constant six-coordinate translation")
    K = B6.transpose() * K0 * B6
    J2 = m.polynomial_power_kernel(K, 2)
    J3 = m.polynomial_power_kernel(K, 3)
    B11, B16 = (binomial_translation(n, BASE_POINT) for n in (11, 16))
    require(J2 == B11.transpose() * m.polynomial_power_kernel(K0, 2) * B11,
            "Full original quadratic coefficient change")
    require(J3 == B16.transpose() * m.polynomial_power_kernel(K0, 3) * B16,
            "Full original cubic coefficient change")
    require(B11 * binomial_translation(11, -BASE_POINT) == identity(11),
            "Original moment translation invertible")
    require(B16 * binomial_translation(16, -BASE_POINT) == identity(16),
            "Original cubic translation invertible")
    J3inv = J3.inv()
    require(J3inv * J3 == identity(16), "Original translated J3 inverse")
    p = [[K[i, k] if k < 6 else m.ZERO for i in range(6)]
         for k in range(order+1)]
    y = [[m.ONE if i == k else m.ZERO for i in range(6)]
         for k in range(order+1)]
    maps = []
    for k in range(order+1):
        B = fmpq_mat([[p[k][i-l] if 0 <= i-l < 6 else m.ZERO
                       for l in range(11)] for i in range(16)])
        maps.append(J3inv * B * J2)

    g = [m.ZERO] * (order+1)
    for i in range(1, 6):
        for l in range(1, 6):
            if i+l-2 <= order:
                g[i+l-2] += i*l*K[i, l]
    old_g = {2: 24, 3: -8, 4: -2}
    expected_g = [sum((fmpq(v*comb(d, k)*BASE_POINT**(d-k))
                       for d, v in old_g.items() if k <= d), m.ZERO)
                  for k in range(order+1)]
    require(g == expected_g, "True g(s)=-2s^2(s-2)(s+6) after shift")
    require(not g[0] and g[1], "Original minus-six contact is simple")

    def moment(index):
        return [m.sequence(index+k, comb(index+k, k)) for k in range(order+1)]

    def add(A, B):
        return [m.add_vectors(A[k], B[k]) for k in range(order+1)]

    def negative(A):
        return [m.scale_vector(A[k], -1) for k in range(order+1)]

    def lp(tensor, vector):
        return fmpq_mat([[sum((tensor[i+l+k]*vector[k] for k in range(6)), m.ZERO)
                          for l in range(6)] for i in range(6)])

    def contract(tensor, Q):
        return [sum((tensor[i+l+k]*Q[l, k]
                     for l in range(6) for k in range(6)), m.ZERO)
                for i in range(6)]

    def evaluate(jets):
        M = [m.hankel(v) for v in jets]
        KM = [K*X for X in M]
        KMK = [X*K for X in KM]
        tensors, quadratic, tau = [], [], []
        for k in range(order+1):
            lvec, q = fmpq_mat(16, 1), fmpq_mat(6, 6)
            for a in range(k+1):
                lvec += maps[a] * m.column(jets[k-a])
                q += M[a] * K * M[k-a]
            tensors.append(m.values(lvec))
            quadratic.append(q)
            tau.append(sum((m.trace(KM[a]*KM[k-a]) for a in range(k+1)), m.ZERO))
        out = []
        for k in range(order+1):
            N, gamma = 4*quadratic[k], [m.ZERO]*6
            for a in range(k+1):
                N += 6*lp(tensors[a], p[k-a])
                gp = m.values(quadratic[a]*m.column(p[k-a]))
                gc = contract(tensors[a], KMK[k-a])
                gamma = [gamma[i]+2*tau[a]*y[k-a][i]+8*gp[i]-12*gc[i]
                         for i in range(6)]
            KNK = K*N*K
            polar = [sum((KNK[i, l] for i in range(6) for l in range(6)
                           if i+l == d), m.ZERO) for d in range(11)]
            out.append(polar+gamma)
        return out

    # eta is the WHOLE original pure quadratic vector divided by g,
    # not a division of any source by the vanishing parameter g.
    eta = [[m.ZERO]*17 for _ in range(order+1)]
    for k in range(order+1):
        for a in range(k+1):
            b = k-a
            if a < 6 and b < 6:
                for i in range(6):
                    for l in range(6):
                        eta[k][i+l] += 4*p[a][i]*p[b][l]
    pure = [[sum((g[a]*eta[k-a][i] for a in range(k+1)), m.ZERO)
             for i in range(17)] for k in range(order+1)]
    tangent = [moment(0), moment(1)]
    Ft = [evaluate(t) for t in tangent]
    for jets, d in ((tangent[0], 0), (tangent[1], 1),
                    (negative(tangent[0]), 0), (negative(tangent[1]), -1),
                    (add(tangent[0], tangent[1]), 1)):
        value = evaluate(jets)
        require(all(value[k] == [fmpq(d*d)*v for v in pure[k]]
                    for k in range(order+1)),
                "All17 original pure identities N=4gd^2Y and Gamma=0")
    unit_eq = next((i for i in range(11) if eta[0][i]), None)
    require(unit_eq is not None, "Actual original N coordinate eta is a local unit")
    require(all(not eta[k][i] for k in range(order+1) for i in range(11, 17)),
            "All six original Gamma pure terms vanish")

    linear = {}
    for index in range(2, 11):
        Z = moment(index)
        FZ, Fminus = evaluate(Z), evaluate(negative(Z))
        linear[index] = [[[ (FZ[k][i]-Fminus[k][i])/2 for i in range(17)]
                          for k in range(order+1)]]
        for t in range(2):
            both = evaluate(add(tangent[t], Z))
            linear[index].append([
                [both[k][i]-FZ[k][i]-Ft[t][k][i] for i in range(17)]
                for k in range(order+1)])
    coeff = {"pure": pure, "linear": linear, "quadratic": {}}
    columns = j.target_columns(0) + j.target_columns(1)
    colindex = {v: c for c, v in enumerate(columns)}
    require(len(columns) == 155, "All projected output coordinates retained")
    extra = [(a, d-a+2, (index,)) for d in range(3)
             for a in range(d+1) for index in range(2, 11)]
    require(len(extra) == 54 and len(set(extra)) == 54, "All 54 g-multiple rows")
    P = []
    for k in range(order+1):
        A = m.join_columns(j.block(m, coeff, k, 0, 0),
                           j.block(m, coeff, k, 0, 1))
        require(A.nrows() == 170 and A.ncols() == 155,
                "All170 original pure-multiplier rows")
        X = fmpq_mat(224, 155)
        for r in range(170):
            for c in range(155):
                X[r, c] = A[r, c]
        for r, key in enumerate(extra):
            X[170+r, colindex[key]] = g[k]
        P.append(X)

    # Verify every original one-normal source row is eta_i(t) times
    # its g-row.  Conversely eta_unit(t) is invertible over Q[t]_(t),
    # so each g-row is generated by an ACTUAL original source row.
    rows1 = j.source_rows(1)
    one_index = {v: c for c, v in enumerate(j.target_columns(1))}
    for k in range(order+1):
        actual = j.block(m, coeff, k, 1, 1)
        expected = fmpq_mat(918, 135)
        for r, (eq, a, b, normal) in enumerate(rows1):
            key = (a, b+2, normal)
            require(key in one_index, "All one-normal sources stay in output degree<=5")
            expected[r, one_index[key]] = sum(
                (g[q]*eta[k-q][eq] for q in range(k+1)), m.ZERO)
        require(actual == expected, "All918 original one-normal projection rows")
    require(len(j.source_rows(2))+len(j.source_rows(3)) == 5100,
            "All higher-normal source rows accounted for")

    h0_factors = [[-8, 32, -25, 5], [864, 864, 135, 5],
                  [9600, -25472, -3392, 15936, -2888, -936, 153, 50, 5]]
    h0_values = [sum(a*BASE_POINT**k for k, a in enumerate(poly))
                 for poly in h0_factors]
    h0_value = (BASE_POINT**3*(BASE_POINT-2)*h0_values[0]**2
                *h0_values[1]**2*h0_values[2])
    require(h0_value != 0, "The actual original h0 is a local unit at minus six")

    metadata = {
        "actualH0FactorValues": list(map(str, h0_values)),
        "actualH0Value": str(h0_value),
        "actualH0FormulaVerified": True,
        "basePoint": BASE_POINT, "naturalParameter": "t=s+6",
        "originalK": m.ORIGINAL_K,
        "translatedK": [[str(K[i, l]) for l in range(6)] for i in range(6)],
        "originalSixTranslationSHA256": m.matrix_hash(B6),
        "originalMomentTranslationSHA256": m.matrix_hash(B11),
        "originalJ2ChangeVerified": True, "originalJ3ChangeVerified": True,
        "J2SHA256": m.matrix_hash(J2), "J3SHA256": m.matrix_hash(J3),
        "gTaylorCoefficients": [str(v) for v in g],
        "etaLocalUnitOriginalEquationZeroBased": unit_eq,
        "etaLocalUnitConstant": str(eta[0][unit_eq]),
        "etaTaylorSHA256": m.matrix_hash(fmpq_mat(eta)),
        "all17OriginalEquationsRetained": True,
        "all170OriginalPureMultiplierRowsRetained": True,
        "all918OriginalOneNormalRowsVerified": True,
        "all5100HigherNormalProjectionRowsZeroByDegree": True,
        "all6188OriginalProjectedSourcesRetained": True,
        "all54AddedRowsAreGMULTIPLES": True,
        "noDivisionByG": True,
        "localGenerationBothDirectionsVerified": True,
        "targetIsActualInverseBinomialSquare": True,
        "projectedOutputDimension": 155, "matrixShape": [224, 155],
        "coefficientSHA256": [m.matrix_hash(X) for X in P]
    }
    return P, metadata


def unit_schur_step(m, series, exponent):
    """Invert only actual constant-unit RHS, verify full convolution."""
    M0 = series[0]
    rows, cols = M0.nrows(), M0.ncols()
    rr, rank = M0.rref()
    piv = m.pivot_columns(rr, rank)
    if not rank:
        require(m.matrix_zero(M0), "Zero-rank constant matrix")
        return series, {"exponent": exponent, "shape": [rows, cols],
                        "rank": 0, "allUnitConvolutionsVerified": True,
                        "schurSHA256": [m.matrix_hash(X) for X in series]}
    rrT, rT = m.submatrix(M0, range(rows), piv).transpose().rref()
    require(rT == rank, "Actual column basis rank")
    rowpiv = m.pivot_columns(rrT, rank)
    rowset, colset = set(rowpiv), set(piv)
    otherrows = [r for r in range(rows) if r not in rowset]
    othercols = [c for c in range(cols) if c not in colset]
    U = [m.submatrix(X, rowpiv, piv) for X in series]
    V = [m.submatrix(X, rowpiv, othercols) for X in series]
    W = [m.submatrix(X, otherrows, piv) for X in series]
    Z = [m.submatrix(X, otherrows, othercols) for X in series]
    determinant = U[0].det()
    require(determinant, "Actual constant unit determinant")
    Y = []
    for k in range(len(series)):
        rhs = fmpq_mat(V[k])
        for a in range(1, k+1):
            rhs -= U[a]*Y[k-a]
        value = U[0].solve(rhs, algorithm="dixon")
        require(U[0]*value == rhs, "All constant-unit original RHS rows")
        Y.append(value)
    for k in range(len(series)):
        lhs = fmpq_mat(rank, len(othercols))
        for a in range(k+1):
            lhs += U[a]*Y[k-a]
        require(lhs == V[k], "Complete original U(t)Y(t)=V(t) convolution")
    S = []
    for k in range(len(series)):
        value = fmpq_mat(Z[k])
        for a in range(k+1):
            value -= W[a]*Y[k-a]
        S.append(value)
    require(m.matrix_zero(S[0]), "All residual constant Schur rows zero")
    return S, {
        "exponent": exponent, "shape": [rows, cols], "rank": rank,
        "unitRows": rowpiv, "unitColumns": piv,
        "unitDeterminant": rational_bit_record(determinant),
        "unitConstantSHA256": m.matrix_hash(U[0]),
        "actualUnitRightHandSideColumns": len(othercols),
        "fullInverseNotConstructed": True,
        "allUnitConvolutionsVerified": True,
        "unitSolutionSHA256": [m.matrix_hash(X) for X in Y],
        "schurSHA256": [m.matrix_hash(X) for X in S]
    }


def local_profile(m, coefficients, result, save):
    params = result["parameters"]
    series = coefficients
    generic = GENERIC_PROJECTION_RANK
    covered = 0
    exact_positive_length = 0
    counts = []
    for exponent in range(len(coefficients)):
        residual, phase = unit_schur_step(m, series, exponent)
        rank = phase["rank"]
        covered += rank
        require(covered <= generic, "Actual constant ranks respect paid generic projection rank")
        if exponent:
            exact_positive_length += exponent*rank
            counts.append([exponent, rank])
        phase["cumulativeCoveredRank"] = covered
        phase["positiveLengthSoFar"] = exact_positive_length
        params["exactTaylorPhases"].append(phase)
        params["lastCompletedExponent"] = exponent
        save()
        if covered == generic:
            require(all(m.matrix_zero(X) for X in residual),
                    "Residual jets vanish after complete generic rank reached")
            params.update({
                "projectedPositiveExponentCounts": counts,
                "projectionGenericRankReached": True,
                "projectedTorsionLengthExact": exact_positive_length,
                "projectedTorsionLengthLowerBound": exact_positive_length,
                "projectedFreeRank": coefficients[0].ncols()-generic,
                "allTaylorSchurIdentitiesVerified": True})
            return
        if exponent+1 == len(coefficients):
            # Every unresolved invariant factor has exponent at least N+1.
            lower = exact_positive_length+(exponent+1)*(generic-covered)
            params.update({
                "projectedPositiveExponentCounts": counts,
                "projectionGenericRankReached": False,
                "unresolvedPositiveInvariantFactors": generic-covered,
                "projectedTorsionLengthExact": None,
                "projectedTorsionLengthLowerBound": lower,
                "projectedFreeRank": coefficients[0].ncols()-generic,
                "allTaylorSchurIdentitiesVerified": True})
            return
        require(m.matrix_zero(residual[0]), "Only a genuinely common t factor is divided")
        series = residual[1:]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--generator", required=True)
    parser.add_argument("--jet-actions", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--remaining-seconds", type=float, default=60.0)
    parser.add_argument("--memory-mib", type=int, default=1024)
    parser.add_argument("--max-order", type=int, default=4)
    args = parser.parse_args()
    require(args.remaining_seconds > 0 and 512 <= args.memory_mib <= 2048
            and args.max_order == 4, "Fixed bounded original minus-six interface")
    require(sha_file(args.generator) == GENERATOR_SHA, "Pinned original generator")
    require(sha_file(args.jet_actions) == ACTIONS_SHA, "Pinned source/target monomial conventions")
    resource.setrlimit(resource.RLIMIT_AS,
                       (args.memory_mib*1024**2, args.memory_mib*1024**2))
    m = module_at("r150_minus_six_original_generator", args.generator)
    j = module_at("r150_minus_six_original_actions", args.jet_actions)
    started = time.monotonic()
    result = {
        "format": FORMAT, "status": "started",
        "scriptSHA256": sha_file(__file__), "arithmetic": "exact rational python-flint",
        "parameters": {
            "basePoint": BASE_POINT, "naturalParameter": "t=s+6",
            "maxTaylorOrder": args.max_order,
            "sharedRemainingSeconds": args.remaining_seconds,
            "memoryMiB": args.memory_mib,
            "inputSourceSHA256": {"generator": GENERATOR_SHA, "jetActions": ACTIONS_SHA},
            "paidFullConstantRank": PAID_CONSTANT_FULL_RANK,
            "paidFullGenericRank": 4354,
            "paidProjectedGenericRank": GENERIC_PROJECTION_RANK,
            "paidFullLocalLengthUpperBound": PAID_FULL_LOCAL_LENGTH_UPPER,
            "fullMatrixNotRecomputed": True, "oldNormalFormsNotRecomputed": True,
            "newFiniteFieldComputationPerformed": False,
            "largeDataUploadedOrCommitted": False,
            "exactTaylorPhases": []
        }
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    def save():
        result["elapsedSeconds"] = time.monotonic()-started
        raw = json.dumps(result, sort_keys=True, separators=(",", ":")).encode()
        require(len(raw) < 100000, "Only small source and exact receipt are persistent")
        temporary = out.with_name(out.name+".tmp")
        temporary.write_bytes(raw)
        temporary.replace(out)

    def stop(signum, frame):
        raise TimeoutError("Shared original minus-six projection budget exhausted")

    signal.signal(signal.SIGALRM, stop)
    signal.signal(signal.SIGTERM, stop)
    signal.setitimer(signal.ITIMER_REAL, args.remaining_seconds)
    try:
        coefficients, metadata = make_original_projection(m, j, args.max_order)
        result["parameters"].update(metadata)
        require(coefficients[0].rank() == 133, "Paid exact minus-six projected constant rank")
        result["parameters"]["paidProjectedConstantRankVerified"] = 133
        save()
        local_profile(m, coefficients, result, save)
        p = result["parameters"]
        require(p["projectedTorsionLengthLowerBound"] <= PAID_FULL_LOCAL_LENGTH_UPPER,
                "Exact quotient length cannot exceed paid full original upper bound")
        equality = (p["projectionGenericRankReached"]
                    and p["projectedTorsionLengthExact"] == PAID_FULL_LOCAL_LENGTH_UPPER)
        p.update({
            "projectionLengthMatchesFullOriginalUpperBound": equality,
            "fullOriginalLocalLengthExactIfMatched": PAID_FULL_LOCAL_LENGTH_UPPER if equality else None,
            "originalWKernelLengthUpperBound":
                PAID_FULL_LOCAL_LENGTH_UPPER-p["projectedTorsionLengthLowerBound"],
            "allTransverseSquareOutputsLocallyInOriginalSource": equality,
            "allNineActualTargetsLocallyInOriginalSource": equality,
            "h0IsLocalUnitAtMinusSix": True,
            "noGlobalPolynomialMembershipClaimed": True,
            "noNewFullOriginalSourceSolutionClaimed": True,
            "conclusionUsesExactOriginalProjectionQuotientSequence": True})
        result["status"] = "completed"
    except BaseException as exc:
        result["status"] = "incomplete"
        result["error"] = type(exc).__name__+": "+str(exc)
        raise
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        save()
        raw = out.read_bytes()
        print(json.dumps({
            "status": result["status"], "receipt": str(out),
            "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "elapsedSeconds": result["elapsedSeconds"],
            "projectedLength": result["parameters"].get("projectedTorsionLengthExact"),
            "localTargetsProved": result["parameters"].get(
                "allNineActualTargetsLocallyInOriginalSource", False)},
            sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
