class TailScalar:
    """Carriers of the ORIGINAL exact Hold reference, never a new target a."""
    def __init__(self, a, paths):
        import gzip
        report = json.loads(a.node_report.read_text())
        if sha(a.scalar_input) != report['input_sha256']:
            raise ValueError('Tail reference must use the same original scalar input')
        raw = a.scalar_input.read_bytes()
        data = json.loads(gzip.decompress(raw) if str(a.scalar_input).endswith('.gz') else raw)
        module = load('actions_tail_original_fullhold', paths['scalar_source'])
        self.full = module.FullHold(data, paths['integer_source'], paths['hold_source'], panels=128)
        self.nodes = [(F(v['S_coefficient']), F(v['constant'])) for v in report['true_scalar_nodes']]
        self.metadata = self.full.metadata()
        self.height = None
        self.maximum_box_width = {key: 0. for key in ('a', 'z', 'ap', 'zp', 'app', 'zpp', 'kappa', 'alpha')}

    def _boxed(self, lo, hi):
        return self.full.o.box(F(lo), F(hi))

    def angle_curvature(self, sbox):
        p, h = self.full, self.full.h
        o, S = p.o, h.S
        lo, hi = F(sbox[0], S), F(sbox[1], S)
        if sbox == p.S:
            return h.scale(p.pi, -F(1, 2)), h.interval(F(0))
        # Continuous alpha/kappa at a segment boundary.  Transport only the
        # tiny time-box uncertainty with analytic global derivative bounds.
        kmax = F(5, 2)
        kprime = F(4653, 1000)*F(15, 8)/p.f
        endpoint_k = [p.K, h.interval(p.kn), h.interval(p.kn),
                      h.interval(p.kp), h.interval(p.kp), h.interval(F(0))]
        for j, boundary in enumerate(p.time):
            left, right = F(boundary[0], S), F(boundary[1], S)
            if lo <= right and hi >= left:
                fee = max(abs(lo-right), abs(hi-left))
                return (h.add(p.alpha[j], self._boxed(-kmax*fee, kmax*fee)),
                        h.add(endpoint_k[j], self._boxed(-kprime*fee, kprime*fee)))
        j = next((i for i in range(5) if lo > F(p.time[i][1], S)
                  and hi < F(p.time[i+1][0], S)), None)
        if j is None:
            raise ValueError('Tail time was not assigned to one exact Hold segment')
        tbox = o.subtract(sbox, p.time[j])
        if j not in p.ramps:
            k = p.kn if j == 1 else p.kp
            return o.subtract(p.alpha[j], h.scale(tbox, k)), h.interval(k)
        ramp = p.ramps[j]
        tl, th = F(tbox[0], S), F(tbox[1], S)
        mid, radius = (tl+th)/2, (th-tl)/2
        u = mid/ramp.width
        smooth = 10*u**3-15*u**4+6*u**5
        k = h.add(h.scale(ramp.left, 1-smooth), h.scale(ramp.right, smooth))
        return (h.add(ramp.angle(mid), self._boxed(-kmax*radius, kmax*radius)),
                h.add(k, self._boxed(-kprime*radius, kprime*radius)))

    def at(self, sbox):
        p, h = self.full, self.full.h
        radius, increment = p.at_box(sbox)
        if increment is None:
            raise ValueError('This tail diagnostic starts strictly after the original Hold cut')
        alpha, k = self.angle_curvature(sbox)
        ap, zp = h.sine_cosine(alpha)
        if sbox == p.S:
            ap, zp, k = h.interval(F(-1)), h.interval(F(0)), h.interval(F(0))
        z = h.add(h.interval(self.height), p.o.subtract(increment, p.height_increment))
        boxes = dict(a=radius, z=z, ap=ap, zp=zp,
            app=h.neg(h.multiply(k, zp)), zpp=h.multiply(k, ap), kappa=k, alpha=alpha)
        for key, box in boxes.items():
            self.maximum_box_width[key] = max(self.maximum_box_width[key], float(F(box[1]-box[0], h.S)))
        return {key: p.carrier(box) for key, box in boxes.items()}

    def stage_box(self, cell, u):
        p = self.full
        left, right = self.nodes[cell], self.nodes[cell+1]
        uu = F(float(u))
        return p.affine_time((1-uu)*left[0]+uu*right[0], (1-uu)*left[1]+uu*right[1])


def synth_batch(o, y):
    cv = o._trig_values(np.stack((y[:, :o.M+1], y[:, 2*o.M+1:]), axis=1), 'cos')
    sv = o._trig_values(y[:, o.M+1:2*o.M+1], 'sin')
    out = np.empty((len(y), o.N, 3))
    out[:, :, 0], out[:, :, 1], out[:, :, 2] = cv[:, 0], sv, cv[:, 1]
    return out


def parent_fields(o, prepared, observed, times):
    """Unchanged original quintic plus complete analytic lift at these times."""
    times = np.asarray(times)
    cells = np.clip(np.searchsorted(o.mesh, times, side='right')-1, 0, o.J-2)
    widths = o.mesh[cells+1]-o.mesh[cells]
    local = (times-o.mesh[cells])/widths
    weights = np.array([observed.hermite_weights(h, u) for h, u in zip(widths, local)])
    endpoints = np.stack((prepared.jets[cells], prepared.jets[cells+1]), axis=1).reshape((-1, 6, o.n))
    jets = np.einsum('bqc,bcn->bqn', weights, endpoints)
    y, u, acc = jets[:, 0], jets[:, 1], jets[:, 2]
    V, T = o._linear_fields(y, u)
    AA, VT = o._linear_fields(u, acc)
    EE = o._angular_second_batch(y)
    X = synth_batch(o, y)
    lift = np.array([o._lift_scalar(float(s)) for s in times])
    for value, radial, vertical in ((X, 3, 0), (V, 4, 1), (AA, 5, 2)):
        value += lift[:, radial, None, None]*prepared.er[None]
        value[:, :, 2] += lift[:, vertical, None]*prepared.height
    T += lift[:, 3, None, None]*(prepared.rho[:, None]*prepared.et)[None]
    VT += lift[:, 4, None, None]*(prepared.rho[:, None]*prepared.et)[None]
    EE += lift[:, 3, None, None]*(prepared.rho_phi[:, None]*prepared.et
                                   -prepared.rho[:, None]**2*prepared.er)[None]
    return dict(X=X, V=V, T=T, AA=AA, VT=VT, EE=EE)


def reference_fields(prepared, scalar):
    scalar = {key: np.asarray([row[key] for row in scalar]) for key in scalar[0]}
    er, et = prepared.er, prepared.et
    rho, rhop = prepared.rho, prepared.rho_phi
    result = {}
    for name, radial, vertical in (('X', 'a', 'z'), ('V', 'ap', 'zp'), ('AA', 'app', 'zpp')):
        value = scalar[radial][:, None, None]*er[None]
        value[:, :, 2] += scalar[vertical][:, None]
        result[name] = value
    result['T'] = scalar['a'][:, None, None]*(rho[:, None]*et)[None]
    result['VT'] = scalar['ap'][:, None, None]*(rho[:, None]*et)[None]
    result['EE'] = scalar['a'][:, None, None]*(rhop[:, None]*et-rho[:, None]**2*er)[None]
    return result


def parent_observed_fields(o, prepared, start, stop):
    """Preserve the actual legacy/added observation map in the finite trial."""
    z = o.physical_jet_batch(prepared, start, stop)
    y = o._stage_triplet(prepared.jets, start, stop)[0]
    X = synth_batch(o, y)
    lift = o.lift_scalar[start:stop]
    X += lift[:, 3, None, None]*prepared.er[None]
    X[:, :, 2] += lift[:, 0, None]*prepared.height
    return dict(X=X, V=z['Fs'], T=z['Fphi'], AA=z['Fss'], VT=z['Fsphi'], EE=z['Fphiphi'])


def arbitrary_point_fields(o, prepared, observed, point):
    """Original complete six jets at one (cell,u,phi), in rotating frame."""
    cell, u, phi = int(point[0]), float(point[1]), float(point[2])
    h = o.mesh[cell+1]-o.mesh[cell]
    s = float(o.mesh[cell]+h*u)
    y, v, acc = observed.hermite_weights(h, u)@prepared.jets[cell:cell+2].reshape(6, o.n)
    co = np.r_[1., np.cos(phi*o.freq)]
    si = np.sin(phi*o.freq)
    def synth(q):
        return np.array([co@q[:o.M+1], si@q[o.M+1:2*o.M+1], co@q[2*o.M+1:]])
    def angular(q, order=1):
        rr, tt, zz = q[:o.M+1], q[o.M+1:2*o.M+1], q[2*o.M+1:]
        R, T = co@rr, si@tt
        Rp, Tp, Zp = -si@(o.freq*rr[1:]), co[1:]@(o.freq*tt), -si@(o.freq*zz[1:])
        if order == 1:
            return np.array([Rp-T, Tp+R, Zp])
        return np.array([-co[1:]@(o.freq**2*rr[1:])-2*Tp-R,
            -si@(o.freq**2*tt)+2*Rp-T, -co[1:]@(o.freq**2*zz[1:])])
    rho = 1+co[1:]@(o.qfreq*prepared.core)
    rhop = -si@(o.freq*o.qfreq*prepared.core)
    delta = si@((o.qfreq/o.freq)*prepared.core)
    er = np.array([np.cos(delta), np.sin(delta), 0.])
    et = np.array([-np.sin(delta), np.cos(delta), 0.])
    chi, cp, cpp, f, fp, fpp = o._lift_scalar(s)
    X, V, AA = synth(y)+f*er, synth(v)+fp*er, synth(acc)+fpp*er
    X[2] += chi*prepared.height
    V[2] += cp*prepared.height
    AA[2] += cpp*prepared.height
    fields = dict(X=X, V=V, T=angular(y)+f*rho*et, AA=AA,
        VT=angular(v)+fp*rho*et, EE=angular(y, 2)+f*(rhop*et-rho*rho*er))
    point_prepared = SimpleNamespace(er=er[None], et=et[None], rho=np.array([rho]),
                                    rho_phi=np.array([rhop]))
    return {key: value[None, None, :] for key, value in fields.items()}, point_prepared, s


def numerical_point_geometry(fields):
    X, V, T, AA, VT, EE = [fields[key][0, 0] for key in ('X', 'V', 'T', 'AA', 'VT', 'EE')]
    normal = np.cross(V, T)
    area2 = float(normal@normal)
    if area2 <= 0:
        raise FloatingPointError('A blend trial lost immersion at a permanent manifest point')
    normal /= np.sqrt(area2)
    E, B, G = V@V, V@T, T@T
    e, f, g = normal@AA, normal@VT, normal@EE
    trace = (e*G+g*E-2*f*B)/area2
    gauss = (e*g-f*f)/area2
    curvature = .5*(abs(trace)+np.sqrt(max(0., trace*trace-4*gauss)))
    return dict(maximum_absolute_principal_curvature=float(curvature),
                radius_squared=float(X@X), area_squared=area2)


def smooth_weights(times, left, right):
    width = right-left
    u = np.clip((np.asarray(times)-left)/width, 0., 1.)
    w = 10*u**3-15*u**4+6*u**5
    wp = 30*u*u*(1-u)**2/width
    wpp = 60*u*(1-u)*(1-2*u)/(width*width)
    inside = (times > left) & (times < right)
    return w, np.where(inside, wp, 0.), np.where(inside, wpp, 0.)


def linearized_material_mode(radius, radial_speed, vertical_speed, kappa, mode):
    """R669 real parity pair (B sin(m theta), C cos(m theta)).

    Returns A and B in Z'=A Z+B(e_m,f_m,g_m), with
    Z=(B,C+a*a'/(2*z')*g_m).  These are MATERIAL-angle coefficients,
    not the stored finite physical-phi Fourier coefficients.  No numerical
    integration or scalar/field evaluation is performed by this helper.
    """
    aa, b, c, k, m = radius, radial_speed, vertical_speed, kappa, int(mode)
    if aa <= 0 or c <= 0 or m < 1:
        raise ValueError('The regular material-mode chart requires a>0 and z_axis_prime>0')
    A = np.array([[-(m*m-1)*b/aa, m*c/aa],
                  [-m*(m*m-1)*b*b/(aa*c), m*m*b/aa]])
    forcing = np.array([[0., 1., 0.],
                        [1/(2*c), m*b/c, -aa*k/(2*c*c)]])
    return A, forcing


def blend_fields(parent, reference, times, left, right, step):
    w, wp, wpp = [v[:, None, None] for v in smooth_weights(times, left, right)]
    d = {key: reference[key]-parent[key] for key in parent}
    return dict(X=parent['X']+step*w*d['X'],
        V=parent['V']+step*(wp*d['X']+w*d['V']),
        T=parent['T']+step*w*d['T'],
        AA=parent['AA']+step*(wpp*d['X']+2*wp*d['V']+w*d['AA']),
        VT=parent['VT']+step*(wp*d['T']+w*d['VT']),
        EE=parent['EE']+step*w*d['EE'])


def numerical_state():
    return dict(weighted_gram_sse=0., spectral_phi_sum=0., max_relative_gram=0.,
        maximum_absolute_principal_curvature=0., maximum_point_radius_squared=0.,
        minimum_relative_determinant=None, worst_metric=None, worst_curvature=None)


def accumulate_numerical(state, fields, o, p, stages, weights, epsilon=.001, scale=.05):
    X, V, T, AA, VT, EE = [fields[key] for key in ('X', 'V', 'T', 'AA', 'VT', 'EE')]
    dot = lambda x, y: np.einsum('bni,bni->bn', x, y)
    Eg, Fg, Gg = dot(V, V), dot(V, T), dot(T, T)
    ar = o.a[stages, None]*p.rho[None]
    e, f, g = Eg-1, Fg/ar, Gg/(ar*ar)-1
    root = np.sqrt((e-g)**2+4*f*f)
    lp, lm = .5*(e+g+root), .5*(e+g-root)
    norms = np.maximum(np.abs(lp), np.abs(lm))
    state['weighted_gram_sse'] += float(weights[stages]@((e*e+2*f*f+g*g)@o.multiplicity))
    point_phi = ((lp*lp+epsilon*epsilon)/(scale*scale))**4+((lm*lm+epsilon*epsilon)/(scale*scale))**4
    state['spectral_phi_sum'] += float(weights[stages]@(point_phi@o.multiplicity))
    det = (1+e)*(1+g)-f*f
    state['minimum_relative_determinant'] = float(det.min()) if state['minimum_relative_determinant'] is None else min(state['minimum_relative_determinant'], float(det.min()))
    address = lambda at: dict(stage=int(stages[at[0]]), s=float(o.times[stages[at[0]]]),
        phi=float(o.phi[at[1]]), parent_cell=int(o.observation_cells[stages[at[0]]]))
    at = np.unravel_index(int(np.argmax(norms)), norms.shape)
    if norms[at] > state['max_relative_gram']:
        state['max_relative_gram'] = float(norms[at])
        state['worst_metric'] = dict(**address(at), components=[float(e[at]), float(f[at]), float(g[at])])
    cross = np.cross(V, T)
    area2 = dot(cross, cross)
    if np.any(area2 <= 0):
        raise FloatingPointError('A numerical blend trial lost immersion at an observation point')
    normal = cross/np.sqrt(area2)[..., None]
    ii, jj, kk = dot(normal, AA), dot(normal, VT), dot(normal, EE)
    trace = (ii*Gg+kk*Eg-2*jj*Fg)/area2
    gauss = (ii*kk-jj*jj)/area2
    gap = np.sqrt(np.maximum(0., trace*trace-4*gauss))
    curvature = .5*(np.abs(trace)+gap)
    at = np.unravel_index(int(np.argmax(curvature)), curvature.shape)
    if curvature[at] > state['maximum_absolute_principal_curvature']:
        state['maximum_absolute_principal_curvature'] = float(curvature[at])
        state['worst_curvature'] = address(at)
    state['maximum_point_radius_squared'] = max(state['maximum_point_radius_squared'], float(dot(X, X).max()))


