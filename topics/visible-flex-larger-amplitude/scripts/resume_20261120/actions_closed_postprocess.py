def endpoint_command(a, paths, context):
    """One exact last-cell height coefficient read; no full field scan."""
    started = time.monotonic()
    if a.out.exists():
        raise FileExistsError('Use a fresh endpoint report')
    with np.load(a.bundle, allow_pickle=False) as data:
        jets = np.array(data['qjets'][-2:, :, :])
        M = (jets.shape[-1]-2)//3
        width, height = F(float(data['width'])), F(float(data['Hcap']))
        end_carrier, radius_carrier = float(data['mesh'][-1]), float(data['radius'])
    report = json.loads(a.node_report.read_text())
    if report['scalar']['source_sha256'] != FULLHOLD_SHA or sha(paths['scalar_source']) != FULLHOLD_SHA:
        raise ValueError('The endpoint theorem uses the stated exact FullHold curvature law')
    if report['S_carrier'] != end_carrier or report['radius_carrier'] != radius_carrier:
        raise ValueError('Endpoint coefficients need the same exact Hold endpoint and node model')
    nodes = [(F(v['S_coefficient']), F(v['constant'])) for v in report['true_scalar_nodes'][-2:]]
    if nodes[-1] != (F(1), F(0)) or nodes[0][0] != nodes[1][0]:
        raise ValueError('This compact read requires the original last-cell width independent of S')
    h = nodes[1][1]-nodes[0][1]
    if h <= 0 or width <= 0 or np.any(jets[-1] != 0):
        raise ValueError('Keep the original positive width and complete zero terminal q jet')
    Z = [[F(float(value)) for value in row[2*M+1:]] for row in jets[0]]
    powers = {3: [], 4: [], 5: []}
    for y, v, acc in zip(*Z):
        powers[3].append((10*y+4*h*v+h*h*acc/2)/h**3)
        powers[4].append((-15*y-7*h*v-h*h*acc)/h**4)
        powers[5].append((6*y+3*h*v+h*h*acc/2)/h**5)
    powers[3][0] -= 10*height/width**3
    powers[4][0] += 15*height/width**4
    powers[5][0] -= 6*height/width**5
    out_width = F(report['scalar']['durations_exact'][-1])
    kp = F(3, 2)
    target = -kp/(2*out_width**3)
    rows = []
    for order, coefficients in powers.items():
        l1 = sum(map(abs, coefficients), F(0))
        angular = sum(map(abs, coefficients[1:]), F(0))
        rows.append(dict(order=order, coefficients_exact=[str(v) for v in coefficients],
            constant_exact=str(coefficients[0]), angular_l1_exact=str(angular),
            all_coefficients_zero=all(v == 0 for v in coefficients),
            whole_cell_height_term_upper_exact=str(l1*h**order),
            whole_cell_velocity_term_upper_exact=str(order*l1*h**(order-1)),
            whole_cell_acceleration_term_upper_exact=str(order*(order-1)*l1*h**(order-2))))
    output = dict(schema='fullclosed-last-cell-height-powers-actions-v1', execution=context,
        source_sha256=sha(__file__), bundle_sha256=sha(a.bundle), node_report_sha256=sha(a.node_report),
        last_cell=len(report['true_scalar_nodes'])-2, scalar_endpoint_equals_model_endpoint=True,
        endpoint_definition='T=FullHold.time[-1]=exact model S; width is the lift transition, not a flat metric collar',
        last_cell_width_exact=str(h), lift_width_exact=str(width), out_ramp_width_exact=str(out_width),
        exact_last_two_symbolic_nodes=[[str(alpha), str(beta)] for alpha, beta in nodes],
        last_cell_S_coefficient_difference_exact=str(nodes[1][0]-nodes[0][0]),
        width_derivation='(alpha_last-alpha_prev)*S+(beta_last-beta_prev); S coefficient is exactly zero',
        last_cell_width_taken_from_float_mesh_difference=False,
        coefficients_are_true_symbolic_mesh_field_coefficients=True,
        supplied_location_manifests=read_manifest_locations(a),
        positive_curvature_exact=str(kp), H_exact=str(height), angular_modes=M,
        height_polynomial='H+b3(phi)*(T-s)^3+b4(phi)*(T-s)^4+b5(phi)*(T-s)^5 near T',
        coefficients=rows, upward_reference_b5_exact=str(target),
        actual_b5_constant_minus_upward_reference_exact=str(powers[5][0]-target),
        necessary_exact_equations='b3=b4=0; b5 is constant with square kp^2/(4*out_width^6)',
        exact_finite_quintic_root_excluded_by_R669=True,
        positive_metric_error_floor_proved=False, refinement_convergence_excluded=False,
        field_or_metric_scan_performed=False, arithmetic='Exact Fraction from binary coefficients and original symbolic last-cell width',
        seconds=time.monotonic()-started)
    write_json(a.out, output)
    announce(event='last_cell_height_coefficients_returned', report_sha256=sha(a.out),
        bundle_sha256=sha(a.bundle), b3_exactly_zero=rows[0]['all_coefficients_zero'],
        b4_exactly_zero=rows[1]['all_coefficients_zero'], seconds=time.monotonic()-started)


def parse_plan(text):
    result = []
    for item in text.split(','):
        q, radial = (int(v) for v in item.split(':'))
        if radial < 1 or radial & (radial-1):
            raise argparse.ArgumentTypeError('Each radial count must be a positive power of two')
        result.append((q, radial))
    if not result:
        raise argparse.ArgumentTypeError('A nonempty refinement plan is required')
    return result


def common_paths(a):
    work = a.work
    a.bundle = (a.bundle or work/'geometry_path/curvature-qp-spectral-hessian-r22-next-six.npz').resolve()
    a.node_report = (a.node_report or work/'fullclosed_solver/data/fullclosed-hold-warm.json').resolve()
    if a.carrier is not None:
        a.carrier = a.carrier.resolve()
    elif a.command == 'tail' or a.manifest:
        a.carrier = (work/'recover_evidence/gauss6-current-three/same-scalar-gauss-observations.npz').resolve()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    direct = sub.add_parser('direct', help='Complete signed X/V/T geometry, D and held bound')
    tail = sub.add_parser('tail', help='One same-g exact analytic tail blend diagnostic')
    endpoint = sub.add_parser('endpoint', help='Exact last-cell b3/b4/b5 height coefficients only')
    for parser in (direct, tail, endpoint):
        parser.add_argument('--repo', type=Path, required=True)
        parser.add_argument('--work', type=Path, required=True)
        parser.add_argument('--bundle', type=Path)
        parser.add_argument('--node-report', type=Path)
        parser.add_argument('--carrier', type=Path)
        parser.add_argument('--manifest', type=Path, action='append', default=[])
        parser.add_argument('--out', type=Path, required=True)
    direct.add_argument('--plan', type=parse_plan, default=parse_plan('256:1,512:2,1024:4,2048:8'))
    direct.add_argument('--cells', default='all')
    direct.add_argument('--beta', default='1/4')
    direct.add_argument('--target-support', type=float, default=.14)
    direct.add_argument('--low-modes', type=int, default=24)
    direct.add_argument('--taylor-degree', type=int, default=8)
    direct.add_argument('--no-nonplanar', dest='nonplanar', action='store_false')
    direct.set_defaults(nonplanar=True)
    tail.add_argument('--scalar-input', type=Path)
    tail.add_argument('--angles', type=int, default=2048)
    tail.add_argument('--stage-block', type=int, default=64)
    tail.add_argument('--line-trials', type=int, default=8)
    a = p.parse_args()
    context = actions_context()
    common_paths(a)
    np.seterr(over='raise', invalid='raise', divide='raise', under='ignore')
    if a.command == 'direct':
        direct_command(a, source_paths(a.repo), context)
    elif a.command == 'tail':
        a.carrier = (a.carrier or a.work/'recover_evidence/gauss6-current-three/same-scalar-gauss-observations.npz').resolve()
